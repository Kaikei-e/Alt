const expectedVectorHeader = "# Code generated by tauto 0.1.0 from specs/tauto/sovereign-projection; DO NOT EDIT."

// casModel mirrors driver/sovereign_db/read_infra_checkpoints.go and
// rebuild_projection.go in memory for pure unit conformance replay.
type casModel struct {
	exists    bool
	seq       int64
	updatedAt int64
	emptied   bool
}

func (m *casModel) read() (exists bool, seq int64, ts int64) {
	if !m.exists {
		return false, 0, 0
	}
	return true, m.seq, m.updatedAt
}

func (m *casModel) advance(fromExists bool, fromSeq, fromTS, toSeq, writeTS int64) bool {
	if !fromExists {
		if m.exists {
			return false
		}
		m.exists = true
		m.seq = toSeq
		m.updatedAt = writeTS
		return true
	}
	if !m.exists || m.seq != fromSeq || m.updatedAt != fromTS {
		return false
	}
	m.seq = toSeq
	m.updatedAt = writeTS
	return true
}

func (m *casModel) rebuild(rebuildTS int64) {
	m.exists = true
	m.seq = 0
	m.updatedAt = rebuildTS
	m.emptied = true
}

func (m *casModel) wireUpdate(targetSeq, writeTS int64) {
	m.exists = true
	m.seq = targetSeq
	m.updatedAt = writeTS
}

func parseInt64(t *testing.T, s string) int64 {
	t.Helper()
	v, err := strconv.ParseInt(s, 10, 64)
	require.NoError(t, err, "parse int64 %q", s)
	return v
}

func parseBool(t *testing.T, s string) bool {
	t.Helper()
	switch s {
	case "true":
		return true
	case "false":
		return false
	default:
		t.Fatalf("invalid bool %q", s)
		return false
	}
}

func parseHole(t *testing.T, s string) Hole {
	t.Helper()
	if s == "none" {
		return Hole{}
	}
	parts := strings.Split(s, ":")
	require.Len(t, parts, 2, "invalid hole %q", s)
	return Hole{First: parseInt64(t, parts[0]), Last: parseInt64(t, parts[1])}
}

func parseTracker(t *testing.T, s string) Tracker {
	t.Helper()
	if s == "empty" {
		return Tracker{}
	}
	parts := strings.Split(s, ":")
	require.Len(t, parts, 4, "invalid tracker %q", s)
	require.Equal(t, "watch", parts[0], "invalid tracker prefix %q", s)
	return Tracker{
		hole:    Hole{First: parseInt64(t, parts[1]), Last: parseInt64(t, parts[2])},
		ceiling: parseInt64(t, parts[3]),
	}
}

func parseFrontier(t *testing.T, s string) sovereign_db.SequenceGapFrontier {
	t.Helper()
	parts := strings.Split(s, ":")
	require.Len(t, parts, 3, "invalid frontier %q", s)
	return sovereign_db.SequenceGapFrontier{
		Ceiling:  parseInt64(t, parts[0]),
		Xmin:     parseInt64(t, parts[1]),
		HoleOpen: parseBool(t, parts[2]),
	}
}

func parseSeqList(t *testing.T, s string) []int64 {
	t.Helper()
	if s == "-" {
		return []int64{}
	}
	parts := strings.Split(s, ",")
	out := make([]int64, 0, len(parts))
	for _, p := range parts {
		out = append(out, parseInt64(t, p))
	}
	return out
}

func parseRow(t *testing.T, s string) (exists bool, seq int64, ts int64) {
	t.Helper()
	if s == "absent" {
		return false, 0, 0
	}
	parts := strings.Split(s, ":")
	require.Len(t, parts, 3, "invalid row %q", s)
	require.Equal(t, "present", parts[0], "invalid row prefix %q", s)
	return true, parseInt64(t, parts[1]), parseInt64(t, parts[2])
}

func loadVectors(t *testing.T) []string {
	t.Helper()
	raw, err := os.ReadFile("testdata/projection_safety_vectors.txt")
	require.NoError(t, err, "read golden vector file")

	var lines []string
	sc := bufio.NewScanner(bytes.NewReader(raw))
	lineNo := 0
	for sc.Scan() {
		lineNo++
		line := strings.TrimSpace(sc.Text())
		if lineNo == 1 {
			require.Equal(t, expectedVectorHeader, line, "golden vector file must start with generated header")
			continue
		}
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		lines = append(lines, line)
	}
	require.NoError(t, sc.Err())
	return lines
}

func TestConformance_TautoProjectionSafetyVectors(t *testing.T) {
	lines := loadVectors(t)

	var casCount, gapCount, prefixCount int
	for _, line := range lines {
		fields := strings.Split(line, "|")
		require.GreaterOrEqual(t, len(fields), 2, "malformed vector line %q", line)
		switch fields[0] {
		case "PREFIX":
			prefixCount++
			require.Len(t, fields, 6, "PREFIX line %q", line)
			name := fields[1]
			afterSeq := parseInt64(t, fields[2])
			inSeqs := parseSeqList(t, fields[3])
			wantPrefix := parseSeqList(t, fields[4])
			wantHole := parseHole(t, fields[5])

			t.Run("PREFIX/"+name, func(t *testing.T) {
				gotPrefix, gotHole := ContiguousPrefix(events(inSeqs...), afterSeq)
				assert.Equal(t, wantPrefix, seqsOf(gotPrefix))
				assert.Equal(t, wantHole, gotHole)
				assert.Equal(t, wantHole != Hole{}, gotHole.Open())
				if gotHole.Open() {
					for _, e := range gotPrefix {
						assert.Less(t, e.EventSeq, gotHole.First, "proved invariant: every folded event is strictly below hole.First")
					}
				}
			})

		case "GAP":
			gapCount++
			require.GreaterOrEqual(t, len(fields), 3, "GAP line %q", line)
			mode := fields[1]
			name := fields[2]
			switch mode {
			case "step":
				require.Len(t, fields, 8, "GAP|step line %q", line)
				initTracker := parseTracker(t, fields[3])
				hole := parseHole(t, fields[4])
				frontier := parseFrontier(t, fields[5])
				wantAbandon := parseBool(t, fields[6])
				wantNext := parseTracker(t, fields[7])

				t.Run("GAP/step/"+name, func(t *testing.T) {
					tracker := initTracker
					got := tracker.MayAbandon(hole, frontier)
					assert.Equal(t, wantAbandon, got)
					assert.Equal(t, wantNext, tracker)
				})

			case "tick":
				require.Len(t, fields, 10, "GAP|tick line %q", line)
				initTracker := parseTracker(t, fields[3])
				hole := parseHole(t, fields[4])
				f1 := parseFrontier(t, fields[5])
				f2 := parseFrontier(t, fields[6])
				wantAbandon := parseBool(t, fields[7])
				wantProbes := int(parseInt64(t, fields[8]))
				wantNext := parseTracker(t, fields[9])

				t.Run("GAP/tick/"+name, func(t *testing.T) {
					tracker := initTracker
					frontiers := []sovereign_db.SequenceGapFrontier{f1, f2}
					probes := 0
					gotAbandon, _, err := tracker.ProbeAndEvaluate(hole, func(firstSeq, lastSeq int64) (sovereign_db.SequenceGapFrontier, error) {
						assert.Equal(t, hole.First, firstSeq)
						assert.Equal(t, hole.Last, lastSeq)
						require.Less(t, probes, len(frontiers), "unexpected extra frontier probe")
						f := frontiers[probes]
						probes++
						return f, nil
					})
					require.NoError(t, err)
					assert.Equal(t, wantAbandon, gotAbandon)
					assert.Equal(t, wantProbes, probes)
					assert.Equal(t, wantNext, tracker)
				})

			default:
				t.Fatalf("unknown GAP mode %q in %q", mode, line)
			}

		case "CAS":
			casCount++
			require.Len(t, fields, 9, "CAS line %q", line)
			name := fields[1]
			initExists, initSeq, initTS := parseRow(t, fields[2])
			op := fields[3]
			toSeq := parseInt64(t, fields[4])
			writeTS := parseInt64(t, fields[5])
			wantApplied := parseBool(t, fields[6])
			wantExists, wantSeq, wantTS := parseRow(t, fields[7])
			wantEmptied := parseBool(t, fields[8])

			t.Run("CAS/"+name, func(t *testing.T) {
				db := &casModel{exists: initExists, seq: initSeq, updatedAt: initTS}
				tokExists, tokSeq, tokTS := db.read()

				switch {
				case op == "none":
					// No intervening writer.
				case strings.HasPrefix(op, "rebuild:"):
					rebuildTS := parseInt64(t, strings.TrimPrefix(op, "rebuild:"))
					db.rebuild(rebuildTS)
				case strings.HasPrefix(op, "wire_update:"):
					parts := strings.Split(strings.TrimPrefix(op, "wire_update:"), ":")
					require.Len(t, parts, 2)
					db.wireUpdate(parseInt64(t, parts[0]), parseInt64(t, parts[1]))
				case strings.HasPrefix(op, "reuse:"):
					parts := strings.Split(strings.TrimPrefix(op, "reuse:"), ":")
					require.Len(t, parts, 2)
					firstApplied := db.advance(tokExists, tokSeq, tokTS, parseInt64(t, parts[0]), parseInt64(t, parts[1]))
					require.True(t, firstApplied, "precondition: initial advance must consume token")
				case strings.HasPrefix(op, "fabricate_present:"):
					parts := strings.Split(strings.TrimPrefix(op, "fabricate_present:"), ":")
					require.Len(t, parts, 2)
					tokExists = true
					tokSeq = parseInt64(t, parts[0])
					tokTS = parseInt64(t, parts[1])
				default:
					t.Fatalf("unknown CAS op %q", op)
				}

				gotApplied := db.advance(tokExists, tokSeq, tokTS, toSeq, writeTS)
				assert.Equal(t, wantApplied, gotApplied)
				assert.Equal(t, wantExists, db.exists)
				assert.Equal(t, wantSeq, db.seq)
				assert.Equal(t, wantTS, db.updatedAt)
				assert.Equal(t, wantEmptied, db.emptied)
			})

		default:
			t.Fatalf("unknown vector kind %q in %q", fields[0], line)
		}
	}

	assert.GreaterOrEqual(t, casCount, 8, "expected at least 8 CAS vectors")
	assert.GreaterOrEqual(t, gapCount, 9, "expected at least 9 GAP vectors")
	assert.GreaterOrEqual(t, prefixCount, 4, "expected at least 4 PREFIX vectors")
}

// Verify that ProbeAndEvaluate propagates readFrontier errors cleanly without
// corrupting tracker state.
func TestTracker_ProbeAndEvaluatePropagatesErrors(t *testing.T) {
	var tracker Tracker
	hole := Hole{First: 5, Last: 5}
	wantErr := os.ErrInvalid

	abandon, _, err := tracker.ProbeAndEvaluate(hole, func(_, _ int64) (sovereign_db.SequenceGapFrontier, error) {
		return sovereign_db.SequenceGapFrontier{}, wantErr
	})
	require.ErrorIs(t, err, wantErr)
	assert.False(t, abandon)
	assert.Equal(t, Tracker{}, tracker)

	// Error on second probe keeps first sighting intact and returns error.
	calls := 0
	abandon, _, err = tracker.ProbeAndEvaluate(hole, func(_, _ int64) (sovereign_db.SequenceGapFrontier, error) {
		calls++
		if calls == 1 {
			return sovereign_db.SequenceGapFrontier{Ceiling: 100, Xmin: 100, HoleOpen: true}, nil
		}
		return sovereign_db.SequenceGapFrontier{}, wantErr
	})
	require.ErrorIs(t, err, wantErr)
	assert.False(t, abandon)
	assert.Equal(t, Tracker{hole: hole, ceiling: 100}, tracker)
}
