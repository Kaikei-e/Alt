def _create_provider_app(embedder: EmbedderPort | None = None) -> FastAPI:
    """Create a FastAPI app with mocked dependencies for provider verification.

    Registers lightweight stub endpoints for:
    - POST /v1/classify-runs          (classification job submission)
    - GET  /v1/classify-runs/{run_id} (polling a completed classification job)
    - POST /v1/clustering/{run_id}    (legacy-compat stub, see below)

    and mounts the *real* application routers for:
    - POST /v1/runs                   (clustering run submission)
    - GET  /v1/runs/{run_id}          (clustering run poll)
    - POST /v1/extract                (HTML content extraction)
    - POST /v1/classify/coarse        (coarse genre classification)
    - POST /v1/evaluation/genres      (genre classification evaluation)
    - POST /v1/embed                  (text embedding generation)
    - POST /v1/cluster-stories        (agglomerative story clustering)
    - POST /v1/verify                 (card sentence verification)
    with usecase/service dependencies overridden by in-memory fakes and the
    same require_admin_token guard create_app() wires in production, so
    verification also exercises the Authorization header the consumer
    pact now records. An injectable fake embedder can be supplied to verify
    contracts across different embedding dimensions.
    """
    app = FastAPI()
    app.include_router(runs_router, dependencies=[Depends(require_admin_token)])
    app.include_router(
        preprocessing_router,
        prefix="/v1",
        dependencies=[Depends(require_admin_token)],
    )
    app.include_router(evaluation_router, dependencies=[Depends(require_admin_token)])
    app.include_router(embed_router, prefix="/v1", dependencies=[Depends(require_admin_token)])
    app.include_router(
        story_clustering_router,
        prefix="/v1",
        dependencies=[Depends(require_admin_token)],
    )
    app.include_router(verify_router, prefix="/v1", dependencies=[Depends(require_admin_token)])

    app.dependency_overrides[deps.get_submit_run_usecase_dep] = lambda: SubmitRunUsecase(
        submitter=_FakeRunSubmitter(),
    )
    app.dependency_overrides[deps.get_get_run_usecase_dep] = lambda: GetRunUsecase(
        reader=_FakeRunReader(),
    )
    app.dependency_overrides[get_admin_auth_config] = lambda: AdminAuthConfig(
        token=_PROVIDER_ADMIN_TOKEN
    )
    app.dependency_overrides[deps.get_content_extractor_dep] = _FakeContentExtractor
    app.dependency_overrides[deps.get_extract_semaphore_dep] = lambda: asyncio.Semaphore(10)
    app.dependency_overrides[deps.get_coarse_classifier_dep] = _FakeCoarseClassifier
    app.dependency_overrides[deps.get_settings_dep] = lambda: Settings(
        model_id="fake", allow_embedding_drift=True
    )
    app.dependency_overrides[deps.get_session] = lambda: None
    app.dependency_overrides[deps.get_container] = _FakeContainer

    fake_embedder = embedder or HashEmbedder(dim=1024)
    embed_svc = EmbedService(embedder=fake_embedder)
    app.dependency_overrides[deps.get_embedder_dep] = lambda: fake_embedder
    app.dependency_overrides[deps.get_embed_service_dep] = lambda: embed_svc
    app.dependency_overrides[deps.get_story_clusterer_service_dep] = StoryClustererService
    app.dependency_overrides[deps.get_card_verifier_service_dep] = lambda: CardVerifierService(
        embed_service=embed_svc
    )

    # Track provider state to switch mock behavior
    provider_state: dict[str, Any] = {"current": "default"}

    # ---- POST /v1/classify-runs ----
    class ClassifyRunsRequest(BaseModel):
        texts: list[str]

    @app.post("/v1/classify-runs", dependencies=[Depends(require_admin_token)])
    async def create_classification_run(payload: ClassifyRunsRequest) -> dict:
        return {
            "run_id": 1,
            "job_id": "00000000-0000-0000-0000-000000000001",
            "status": "running",
            "result_count": 0,
        }

    # ---- GET /v1/classify-runs/{run_id} ----
    @app.get("/v1/classify-runs/{run_id}", dependencies=[Depends(require_admin_token)])
    async def get_classification_run(run_id: int) -> dict:
        return {
            "run_id": run_id,
            "job_id": "00000000-0000-0000-0000-000000000001",
            "status": "succeeded",
            "result_count": 5,
            "results": [
                {
                    "top_genre": "technology",
                    "confidence": 0.85,
                    "scores": {"technology": 0.85, "science": 0.1},
                }
            ],
        }

    # ---- POST /v1/clustering/{run_id} ----
    # Legacy-compat stub for the frozen pact of recap-worker versions
    # currently recorded as deployed in the Pact Broker (64d94ed2c,
    # 75704ff6...). This endpoint never existed in production traffic --
    # it was a fabricated route introduced by mistake and retired in
    # a9fa386d6 in favour of the real /v1/runs surface below. It is kept
    # here only so provider verification does not 404 against those old
    # consumer pacts while they are still deployed, which would otherwise
    # block can-i-deploy for the *new* recap-worker that retires it.
    # DELETE this stub once recap-worker >= 2ac25ca is recorded as
    # deployed in the Pact Broker.
    @app.post("/v1/clustering/{run_id}")
    async def execute_clustering_legacy_compat(run_id: int) -> dict:
        return {
            "run_id": run_id,
            "job_id": "00000000-0000-0000-0000-000000000001",
            "genre": "technology",
            "status": "succeeded",
            "cluster_count": 3,
            "clusters": [
                {
                    "cluster_id": 0,
                    "size": 5,
                    "top_terms": ["AI"],
                    "representatives": [{"sentence_text": "AI is transforming industries."}],
                }
            ],
        }

    # ---- Provider state registry ----
    async def _set_state(params: dict) -> None:
        provider_state["params"] = params

    registry: StateRegistry = {
        "the classification model is loaded": _set_state,
        "classification job 42 has succeeded": _set_state,
        "the clustering pipeline accepts a new run": _set_state,
        "clustering run 42 has succeeded": _set_state,
        # Legacy-compat: see execute_clustering_legacy_compat above.
        "classified articles are ready for clustering": _set_state,
        # Topic card embedding and clustering provider states:
        "the embedder model is loaded": _set_state,
        "the embedder is ready": _set_state,
        "the story clusterer is ready": _set_state,
        "ready to cluster stories": _set_state,
        # Topic card verification provider states:
        "the card verifier is ready": _set_state,
        "ready to verify cards": _set_state,
        # Extraction and evaluation provider states:
        "the content extractor is ready": _set_state,
        "the evaluation service is ready": _set_state,
    }

    @app.post("/_pact/provider-states")
    async def provider_states(payload: dict) -> dict:
        await dispatch(registry, payload)
        return {"status": "ok"}

    return app


