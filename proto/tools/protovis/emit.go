package main

import (
	"bytes"
	"fmt"
	"go/format"
)

const generatedHeader = "// Code generated by protovis. DO NOT EDIT."

// RenderGo emits the BFF allowlist. The BFF's catch-all default is deny, so
// these two maps are the whole definition of what the proxy will forward.
func RenderGo(list Allowlist) ([]byte, error) {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, "%s\n", generatedHeader)
	buf.WriteString("// Source: the (alt.api.v1.visibility) option on each alt.* service in proto/.\n")
	buf.WriteString("// Regenerate: cd proto/tools/protovis && go run . -desc <buf build output>\n\n")
	buf.WriteString("package server\n\n")

	buf.WriteString("// PublicServices are reachable from the browser through the generic\n")
	buf.WriteString("// /api/v2 proxy. Anything absent here is not proxyable, by default.\n")
	writeGoSet(&buf, "PublicServices", list.Public)

	buf.WriteString("\n// AdminServices are forwardable only through dedicated gated routes that\n")
	buf.WriteString("// apply their own authorization. They are never proxyable generically.\n")
	writeGoSet(&buf, "AdminServices", list.Admin)

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated allowlist: %w", err)
	}
	return src, nil
}

func writeGoSet(buf *bytes.Buffer, name string, services []string) {
	fmt.Fprintf(buf, "var %s = map[string]struct{}{\n", name)
	for _, svc := range services {
		fmt.Fprintf(buf, "\t%q: {},\n", svc)
	}
	buf.WriteString("}\n")
}

// RenderTS emits the frontend allowlist. Admin services are deliberately
// absent: the browser never reaches them through the generic proxy, so
// shipping their names to the bundle would only widen the public surface.
func RenderTS(list Allowlist) ([]byte, error) {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, "%s\n", generatedHeader)
	buf.WriteString("// Source: the (alt.api.v1.visibility) option on each alt.* service in proto/.\n")
	buf.WriteString("// Regenerate: cd proto/tools/protovis && go run . -desc <buf build output>\n\n")
	buf.WriteString("export const PUBLIC_SERVICES = [\n")
	for _, svc := range list.Public {
		fmt.Fprintf(&buf, "\t%q,\n", svc)
	}
	buf.WriteString("] as const;\n")

	return buf.Bytes(), nil
}
