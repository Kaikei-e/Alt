func TestGoldenJSON(t *testing.T) {
	for _, name := range []string{"ok", "fan-in"} {
		t.Run(name, func(t *testing.T) {
			adrs := loadFixture(t, name)
			g := adr.SupersedesGraph(adrs)
			rev := graph.BuildReverse(g)
			out, err := JSONGraph(adrs, g, rev)
			if err != nil {
				t.Fatal(err)
			}
			if !json.Valid(out) {
				t.Fatalf("JSONGraph produced invalid JSON: %s", out)
			}
			golden(t, "json-"+name+".golden", append(out, '\n'))
		})
	}
}

func TestJSONGraphUsesLinksKey(t *testing.T) {
	adrs := loadFixture(t, "ok")
	g := adr.SupersedesGraph(adrs)
	out, err := JSONGraph(adrs, g, graph.BuildReverse(g))
	if err != nil {
		t.Fatal(err)
	}
	var doc map[string]json.RawMessage
	if err := json.Unmarshal(out, &doc); err != nil {
		t.Fatal(err)
	}
	if _, ok := doc["links"]; !ok {
		t.Error(`JSONGraph output missing "links" key (node-link convention)`)
	}
	if _, ok := doc["edges"]; ok {
		t.Error(`JSONGraph output must not use "edges" key — node-link default is "links"`)
	}
}
