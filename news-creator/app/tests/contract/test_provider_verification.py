"""Provider verification tests for news-creator.

Verifies that news-creator fulfills the contracts defined by its consumers:
- pre-processor (via /api/v1/summarize)
- rag-orchestrator (via /api/chat, /api/v1/plan-query)
- acolyte-orchestrator (via /api/v1/summarize, non-streaming)
- recap-worker (via /v1/summary/generate, /v1/summary/generate/batch)

These tests start a real FastAPI app with mocked usecases/gateways
and verify it against pact contracts. Contracts are loaded from either:
- Pact Broker (when PACT_BROKER_BASE_URL is set) — used in CI
- Local filesystem (fallback) — used in local development
"""

