    @pytest.mark.asyncio
    async def test_lifo_promoted_be_not_starved_behind_rt(self) -> None:
        """Context #5: In LIFO mode, promoted BE uses negative timestamp and beats queued RT."""
        sem = HybridPrioritySemaphore(
            total_slots=1,
            rt_reserved_slots=1,
            rt_scheduling_mode="lifo",
            priority_promotion_threshold_seconds=0.04,
            aging_sweep_interval_releases=1,
            guaranteed_be_ratio=0,
            preemption_enabled=False,
        )
        _, holder_sid = await sem.acquire(high_priority=True)

        order: list[str] = []

        async def _worker(label: str, high_priority: bool) -> None:
            _, sid = await sem.acquire(high_priority=high_priority)
            order.append(label)
            sem.release(was_high_priority=high_priority, slot_id=sid)

        be_task = asyncio.create_task(_worker("be_promoted", False))
        await asyncio.sleep(0.06)  # BE ages past promotion threshold
        rt_task = asyncio.create_task(_worker("rt_newer", True))
        await asyncio.sleep(0.01)

        # Trigger aging directly first to inspect LIFO enqueue_time sign
        sem._apply_aging()
        assert len(sem._be_queue) == 0
        assert len(sem._rt_queue) == _TWO_QUEUED
        assert all(req.enqueue_time < 0 for req in sem._rt_queue), (
            f"All LIFO _rt_queue entries must have negative enqueue_time: "
            f"{[r.enqueue_time for r in sem._rt_queue]}"
        )

        sem.release(was_high_priority=True, slot_id=holder_sid)
        await asyncio.gather(be_task, rt_task)
        assert order[0] == "be_promoted", (
            f"Promoted BE was starved in LIFO mode: order={order}"
        )

