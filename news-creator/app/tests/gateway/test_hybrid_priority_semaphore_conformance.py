    @pytest.mark.asyncio
    async def test_cancelled_waiter_purged_synchronously_even_when_lock_contended(
        self,
    ) -> None:
        """Context #6: Cancelled waiter purges queue synchronously without awaiting _lock."""
        sem = HybridPrioritySemaphore(
            total_slots=1,
            rt_reserved_slots=1,
            max_queue_depth=1,
            preemption_enabled=False,
        )
        _, holder_sid = await sem.acquire(high_priority=True)
        waiter = asyncio.create_task(sem.acquire(high_priority=True))
        await asyncio.sleep(0)
        assert len(sem._rt_queue) == 1

        # Hold _lock externally so an `async with self._lock` in except CancelledError
        # would block (and leak on double-cancel).
        await sem._lock.acquire()
        try:
            waiter.cancel()
            await asyncio.sleep(0)
            # Second cancellation while cleanup runs must NOT prevent queue purge!
            waiter.cancel()
            with pytest.raises(asyncio.CancelledError):
                await asyncio.wait_for(waiter, timeout=0.5)
            assert len(sem._rt_queue) == 0, (
                "Cancelled waiter was not purged synchronously while _lock was held"
            )
        finally:
            sem._lock.release()

        sem.release(was_high_priority=True, slot_id=holder_sid)
        assert sem._rt_available == 1

    @pytest.mark.asyncio
    async def test_cancel_in_transit_recovery_resets_consecutive_rt_releases(
        self,
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        """Context #6: _release_slot_to_pool_or_waiter resets _consecutive_rt_releases on BE wake."""
        sem = HybridPrioritySemaphore(
            total_slots=1,
            rt_reserved_slots=1,
            guaranteed_be_ratio=3,
            preemption_enabled=False,
        )
        _, holder_sid = await sem.acquire(high_priority=True)
        rt_waiter = asyncio.create_task(sem.acquire(high_priority=True))
        be_waiter = asyncio.create_task(sem.acquire(high_priority=False))
        await asyncio.sleep(0)

        # Release wakes RT waiter and increments consecutive_rt_releases -> 1
        sem.release(was_high_priority=True, slot_id=holder_sid)
        assert sem._consecutive_rt_releases == 1

        # Cancel RT waiter in-transit -> forwards slot to BE waiter and resets counter to 0
        with caplog.at_level(logging.ERROR, logger=_LOGGER_NAME):
            rt_waiter.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await rt_waiter

        assert sem._consecutive_rt_releases == 0
        _, be_sid = await asyncio.wait_for(be_waiter, timeout=1.0)
        sem.release(was_high_priority=False, slot_id=be_sid)
        assert sem._rt_available == 1
        assert not any(
            "SLOT INVARIANT VIOLATION" in rec.message for rec in caplog.records
        )

