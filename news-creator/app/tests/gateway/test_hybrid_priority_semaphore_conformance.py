"""Conformance oracle and Phase 2 hardening tests for HybridPrioritySemaphore.

Replays every golden vector scenario emitted by the Tauto formal specification
(`specs/tauto/hybrid-priority-semaphore/`) against the real
`HybridPrioritySemaphore` implementation, verifying all 9 state counters at
every transition step plus zero false-positive `SLOT INVARIANT VIOLATION` logs.
Also tests all ADR-001030 Context #1-#6 Phase 2 hardening invariants.
"""

from __future__ import annotations

import asyncio
import contextlib
import logging
import re
import time
from dataclasses import dataclass, field
from pathlib import Path

import pytest

from news_creator.domain.errors import QueueFullError
from news_creator.gateway.hybrid_priority_semaphore import HybridPrioritySemaphore

_VECTORS_PATH = (
    Path(__file__).resolve().parent
    / "testdata"
    / "hybrid_priority_semaphore_vectors.txt"
)
_EXPECTED_HEADER = (
    "# Code generated by tauto 0.1.0 from specs/tauto/hybrid-priority-semaphore; "
    "DO NOT EDIT."
)
_LOGGER_NAME = "news_creator.gateway.hybrid_priority_semaphore"
_UNKNOWN_SLOT_ID = 999_999
_MIN_SCENARIOS = 10
_MIN_STEPS = 80
_TWO_SLOTS = 2
_TWO_QUEUED = 2
_TWO_VIOLATIONS = 2

_ACQUIRE_RE = re.compile(r"^Acquire\((Rt|Be)\)$")
_RELEASE_RE = re.compile(r"^Release\((Rt|Be),(PoolRt|PoolBe)\)$")
_COMPLETE_RE = re.compile(r"^CompleteTransfer\((PoolRt|PoolBe)\)$")
_CANCEL_Q_RE = re.compile(r"^CancelQueued\((Rt|Be)\)$")
_CANCEL_IT_RE = re.compile(r"^CancelInTransit\((PoolRt|PoolBe)\)$")
_WOKE_RE = re.compile(
    r"^(?:ReleasedToWaiter|RecoveredToWaiter)\((Rt|Be),(PoolRt|PoolBe)\)$"
)
_GUAR_RE = re.compile(r"^ReleasedToBeGuaranteed\((PoolRt|PoolBe)\)$")

StateTuple = tuple[int, int, int, int, int, int, int, int, int]


@dataclass(frozen=True)
class VectorStep:
    """Single step in a Tauto-emitted conformance scenario."""

    scenario: str
    index: int
    event: str
    outcome: str
    expected_state: StateTuple


@dataclass
class VectorScenario:
    """Named scenario with config and ordered steps."""

    name: str
    rt_reserved: int
    be_slots: int
    max_queue_depth: int
    guaranteed_be_ratio: int
    steps: list[VectorStep] = field(default_factory=list)


def _load_scenarios() -> list[VectorScenario]:
    if not _VECTORS_PATH.exists():
        return []
    lines = _VECTORS_PATH.read_text(encoding="utf-8").splitlines()
    scenarios: list[VectorScenario] = []
    by_name: dict[str, VectorScenario] = {}
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("|")
        kind = parts[0]
        if kind == "SCENARIO":
            scenario = VectorScenario(
                name=parts[1],
                rt_reserved=int(parts[2]),
                be_slots=int(parts[3]),
                max_queue_depth=int(parts[4]),
                guaranteed_be_ratio=int(parts[5]),
            )
            scenarios.append(scenario)
            by_name[scenario.name] = scenario
        elif kind == "STEP":
            step = VectorStep(
                scenario=parts[1],
                index=int(parts[2]),
                event=parts[3],
                outcome=parts[4],
                expected_state=(
                    int(parts[5]),
                    int(parts[6]),
                    int(parts[7]),
                    int(parts[8]),
                    int(parts[9]),
                    int(parts[10]),
                    int(parts[11]),
                    int(parts[12]),
                    int(parts[13]),
                ),
            )
            by_name[step.scenario].steps.append(step)
        else:
            msg = f"Unknown vector record kind: {kind!r} in line {line!r}"
            raise ValueError(msg)
    return scenarios


def _snapshot(sem: HybridPrioritySemaphore) -> StateTuple:
    held_rt = sum(1 for s in sem._acquired_slots.values() if s.home_pool == "rt")
    held_be = sum(1 for s in sem._acquired_slots.values() if s.home_pool == "be")
    return (
        sem._rt_available,
        held_rt,
        sem._in_transit_rt,
        sem._be_available,
        held_be,
        sem._in_transit_be,
        len(sem._rt_queue),
        len(sem._be_queue),
        sem._consecutive_rt_releases,
    )


def _parse_pool(pool_label: str) -> str:
    pool_map = {"PoolRt": "rt", "PoolBe": "be"}
    if pool_label in pool_map:
        return pool_map[pool_label]
    msg = f"Unknown pool label: {pool_label!r}"
    raise ValueError(msg)


def _parse_prio(prio_label: str) -> bool:
    prio_map = {"Rt": True, "Be": False}
    if prio_label in prio_map:
        return prio_map[prio_label]
    msg = f"Unknown priority label: {prio_label!r}"
    raise ValueError(msg)


class _ScenarioReplayer:
    """Drives a real HybridPrioritySemaphore through a Tauto golden scenario."""

    def __init__(self, scenario: VectorScenario) -> None:
        self.scenario = scenario
        total_slots = scenario.rt_reserved + scenario.be_slots
        self.sem = HybridPrioritySemaphore(
            total_slots=total_slots,
            rt_reserved_slots=scenario.rt_reserved,
            max_queue_depth=scenario.max_queue_depth,
            guaranteed_be_ratio=scenario.guaranteed_be_ratio,
            preemption_enabled=False,
            aging_sweep_interval_releases=10_000,
        )
        self.held_ids: dict[str, list[int]] = {"rt": [], "be": []}
        self.stale_ids: dict[str, list[int]] = {"rt": [], "be": []}
        self.queued_tasks: dict[str, list[asyncio.Task[tuple[float, int]]]] = {
            "rt": [],
            "be": [],
        }
        self.in_transit_tasks: dict[str, list[asyncio.Task[tuple[float, int]]]] = {
            "rt": [],
            "be": [],
        }
        self.completed_snapshots: list[tuple[str, int, StateTuple]] = []
        self.recovery_snapshots: list[tuple[str, StateTuple]] = []
        self._install_observers()

    def _install_observers(self) -> None:
        orig_record = self.sem._record_queued_acquire
        orig_recover = self.sem._release_slot_to_pool_or_waiter

        def _spy_record(
            result: object, start_time: float, high_priority: bool
        ) -> tuple[float, int]:
            wait_time, sid = orig_record(result, start_time, high_priority)
            pool = self.sem._acquired_slots[sid].home_pool
            self.completed_snapshots.append((pool, sid, _snapshot(self.sem)))
            return wait_time, sid

        def _spy_recover(home_pool: str) -> None:
            orig_recover(home_pool)
            self.recovery_snapshots.append((home_pool, _snapshot(self.sem)))

        self.sem._record_queued_acquire = _spy_record  # type: ignore[method-assign]
        self.sem._release_slot_to_pool_or_waiter = _spy_recover  # type: ignore[method-assign]

    def _record_woken_waiter(self, outcome: str) -> None:
        if wm := _WOKE_RE.match(outcome):
            woken_q = "rt" if wm.group(1) == "Rt" else "be"
            woken_pool = _parse_pool(wm.group(2))
            self.in_transit_tasks[woken_pool].append(self.queued_tasks[woken_q].pop(0))
        elif gm := _GUAR_RE.match(outcome):
            woken_pool = _parse_pool(gm.group(1))
            self.in_transit_tasks[woken_pool].append(self.queued_tasks["be"].pop(0))

    async def _step_acquire(self, step: VectorStep, is_rt: bool) -> StateTuple:
        if step.outcome == "RejectedQueueFull":
            with pytest.raises(QueueFullError):
                await self.sem.acquire(high_priority=is_rt)
        elif step.outcome.startswith(("AcquiredImmediate(", "AcquiredFallback(")):
            wait_time, sid = await self.sem.acquire(high_priority=is_rt)
            assert wait_time == 0.0
            pool = self.sem._acquired_slots[sid].home_pool
            self.held_ids[pool].append(sid)
        elif step.outcome.startswith("Enqueued("):
            task = asyncio.create_task(self.sem.acquire(high_priority=is_rt))
            await asyncio.sleep(0)
            assert not task.done(), (
                f"{self.scenario.name} step {step.index}: expected task to enqueue"
            )
            self.queued_tasks["rt" if is_rt else "be"].append(task)
        else:
            msg = f"Unexpected Acquire outcome: {step.outcome}"
            raise AssertionError(msg)
        return _snapshot(self.sem)

    def _step_release(self, step: VectorStep, caller_rt: bool, pool: str) -> StateTuple:
        if step.outcome == "RejectedInvalidRelease":
            bad_sid = (
                self.stale_ids[pool][-1] if self.stale_ids[pool] else _UNKNOWN_SLOT_ID
            )
            self.sem.release(was_high_priority=caller_rt, slot_id=bad_sid)
        else:
            sid = self.held_ids[pool].pop(0)
            self.stale_ids[pool].append(sid)
            self.sem.release(was_high_priority=caller_rt, slot_id=sid)
            self._record_woken_waiter(step.outcome)
        return _snapshot(self.sem)

    async def _step_complete_transfer(self, pool: str) -> StateTuple:
        task = self.in_transit_tasks[pool].pop(0)
        if not self.completed_snapshots:
            await asyncio.sleep(0)
        if not task.done():
            await asyncio.wait_for(task, timeout=1.0)
        match_idx = next(
            i for i, item in enumerate(self.completed_snapshots) if item[0] == pool
        )
        rec_pool, sid, snap = self.completed_snapshots.pop(match_idx)
        assert rec_pool == pool
        self.held_ids[pool].append(sid)
        return snap

    async def _step_cancel_queued(self, prio_label: str) -> StateTuple:
        q_key = "rt" if prio_label == "Rt" else "be"
        task = self.queued_tasks[q_key].pop(0)
        task.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await task
        return _snapshot(self.sem)

    async def _step_cancel_in_transit(self, step: VectorStep, pool: str) -> StateTuple:
        task = self.in_transit_tasks[pool].pop(0)
        task.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await task
        assert self.recovery_snapshots, (
            f"{self.scenario.name} step {step.index}: recovery path did not run"
        )
        rec_pool, snap = self.recovery_snapshots.pop(0)
        assert rec_pool == pool
        self._record_woken_waiter(step.outcome)
        return snap

    def _step_promote(self) -> StateTuple:
        assert self.sem._be_queue, "PromoteBeToRt requires a queued BE waiter"
        oldest = min(self.sem._be_queue, key=lambda r: r.enqueue_time)
        oldest.enqueue_time = (
            time.monotonic() - self.sem._priority_promotion_threshold - 1.0
        )
        self.sem._apply_aging()
        self.queued_tasks["rt"].append(self.queued_tasks["be"].pop(0))
        return _snapshot(self.sem)

    async def execute_step(self, step: VectorStep) -> StateTuple:
        if m := _ACQUIRE_RE.match(step.event):
            return await self._step_acquire(step, _parse_prio(m.group(1)))
        if m := _RELEASE_RE.match(step.event):
            return self._step_release(
                step, _parse_prio(m.group(1)), _parse_pool(m.group(2))
            )
        if m := _COMPLETE_RE.match(step.event):
            return await self._step_complete_transfer(_parse_pool(m.group(1)))
        if m := _CANCEL_Q_RE.match(step.event):
            return await self._step_cancel_queued(m.group(1))
        if m := _CANCEL_IT_RE.match(step.event):
            return await self._step_cancel_in_transit(step, _parse_pool(m.group(1)))
        if step.event == "PromoteBeToRt":
            return self._step_promote()
        msg = f"Unhandled vector event: {step.event!r}"
        raise AssertionError(msg)

    async def cleanup(self) -> None:
        for bucket in (*self.queued_tasks.values(), *self.in_transit_tasks.values()):
            for pending in bucket:
                if not pending.done():
                    pending.cancel()
                    with contextlib.suppress(asyncio.CancelledError):
                        await pending

    async def run(self, caplog: pytest.LogCaptureFixture) -> None:
        caplog.set_level(logging.ERROR, logger=_LOGGER_NAME)
        try:
            for step in self.scenario.steps:
                actual_snap = await self.execute_step(step)
                assert actual_snap == step.expected_state, (
                    f"{self.scenario.name} step {step.index} "
                    f"({step.event} -> {step.outcome}): "
                    f"expected 9-counter state {step.expected_state}, got {actual_snap}"
                )
            violations = [
                rec.message
                for rec in caplog.records
                if "SLOT INVARIANT VIOLATION" in rec.message
            ]
            assert violations == [], (
                f"{self.scenario.name} emitted unexpected SLOT INVARIANT VIOLATION "
                f"logs: {violations}"
            )
        finally:
            await self.cleanup()


_SCENARIOS = _load_scenarios()


class TestTautoConformanceVectors:
    """Golden vector conformance oracle tests."""

    def test_golden_vectors_file_exists_and_has_valid_header(self) -> None:
        """Golden vector file must exist, carry the Tauto header, and cover all scenarios."""
        assert _VECTORS_PATH.exists(), f"Missing golden vectors at {_VECTORS_PATH}"
        lines = _VECTORS_PATH.read_text(encoding="utf-8").splitlines()
        assert lines, "Golden vectors file is empty"
        assert lines[0] == _EXPECTED_HEADER
        assert len(_SCENARIOS) >= _MIN_SCENARIOS
        total_steps = sum(len(sc.steps) for sc in _SCENARIOS)
        assert total_steps >= _MIN_STEPS

    @pytest.mark.asyncio
    @pytest.mark.parametrize(
        "scenario",
        _SCENARIOS,
        ids=[sc.name for sc in _SCENARIOS],
    )
    async def test_replay_scenario(
        self,
        scenario: VectorScenario,
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        """Replay every step of a Tauto golden scenario against HybridPrioritySemaphore."""
        await _ScenarioReplayer(scenario).run(caplog)


class TestPhase2Hardening:
    """Unit tests covering ADR-001030 Context #1-#6 and §3.2 hardening gaps."""

    @pytest.mark.asyncio
    async def test_multi_in_transit_no_false_positive_invariant_error(
        self,
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        """Context #1: Two simultaneous in-transit transfers must not emit SLOT INVARIANT VIOLATION."""
        sem = HybridPrioritySemaphore(
            total_slots=_TWO_SLOTS,
            rt_reserved_slots=1,
            preemption_enabled=False,
            guaranteed_be_ratio=0,
        )
        _, rt1_sid = await sem.acquire(high_priority=True)
        _, be1_sid = await sem.acquire(high_priority=False)

        rt2_task = asyncio.create_task(sem.acquire(high_priority=True))
        be2_task = asyncio.create_task(sem.acquire(high_priority=False))
        await asyncio.sleep(0)

        with caplog.at_level(logging.ERROR, logger=_LOGGER_NAME):
            sem.release(was_high_priority=True, slot_id=rt1_sid)
            sem.release(was_high_priority=False, slot_id=be1_sid)

            status = sem.queue_status()
            assert sem._in_transit_rt == 1
            assert sem._in_transit_be == 1
            assert status["in_transit_slots"] == _TWO_SLOTS
            assert (
                status["available_slots"]
                + status["acquired_slots"]
                + status["in_transit_slots"]
                == status["total_slots"]
            )

        violations = [
            rec.message
            for rec in caplog.records
            if "SLOT INVARIANT VIOLATION" in rec.message
        ]
        assert violations == []

        _, rt2_sid = await asyncio.wait_for(rt2_task, timeout=1.0)
        _, be2_sid = await asyncio.wait_for(be2_task, timeout=1.0)
        assert sem._in_transit_rt == 0
        assert sem._in_transit_be == 0
        sem.release(was_high_priority=True, slot_id=rt2_sid)
        sem.release(was_high_priority=False, slot_id=be2_sid)

    @pytest.mark.asyncio
    async def test_unknown_slot_id_rejected_and_preserves_mutual_exclusion(
        self,
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        """Context #2: Unknown slot_id release must NOT wake queued waiters or violate mutex."""
        sem = HybridPrioritySemaphore(
            total_slots=1,
            rt_reserved_slots=1,
            preemption_enabled=False,
            guaranteed_be_ratio=0,
        )
        _, rt1_sid = await sem.acquire(high_priority=True)
        rt2_task = asyncio.create_task(sem.acquire(high_priority=True))
        await asyncio.sleep(0)

        with caplog.at_level(logging.ERROR, logger=_LOGGER_NAME):
            sem.release(was_high_priority=True, slot_id=_UNKNOWN_SLOT_ID)

        await asyncio.sleep(0)
        assert not rt2_task.done(), "Unknown slot_id must NOT wake queued waiter"
        assert len(sem._acquired_slots) == 1
        assert sem._rt_available == 0
        assert sem._in_transit_rt == 0
        assert any(
            "unknown or already-released" in rec.message for rec in caplog.records
        )

        # Real release wakes RT2 cleanly
        sem.release(was_high_priority=True, slot_id=rt1_sid)
        _, rt2_sid = await asyncio.wait_for(rt2_task, timeout=1.0)
        sem.release(was_high_priority=True, slot_id=rt2_sid)
        assert sem._rt_available == 1

    @pytest.mark.asyncio
    async def test_double_release_rejected_without_waking_waiter_or_phantom_slot(
        self,
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        """Context #2: Releasing the same slot_id twice is rejected as a no-op."""
        sem = HybridPrioritySemaphore(
            total_slots=1,
            rt_reserved_slots=1,
            preemption_enabled=False,
            guaranteed_be_ratio=0,
        )
        _, sid1 = await sem.acquire(high_priority=True)
        w1 = asyncio.create_task(sem.acquire(high_priority=True))
        w2 = asyncio.create_task(sem.acquire(high_priority=True))
        await asyncio.sleep(0)

        sem.release(was_high_priority=True, slot_id=sid1)
        with caplog.at_level(logging.ERROR, logger=_LOGGER_NAME):
            sem.release(was_high_priority=True, slot_id=sid1)

        await asyncio.sleep(0)
        assert w1.done()
        assert not w2.done(), "Double release must NOT wake a second waiter"
        assert len(sem._acquired_slots) == 1
        assert sem._in_transit_rt == 0
        assert any(
            "unknown or already-released" in rec.message for rec in caplog.records
        )

        _, w1_sid = w1.result()
        sem.release(was_high_priority=True, slot_id=w1_sid)
        _, w2_sid = await asyncio.wait_for(w2, timeout=1.0)
        sem.release(was_high_priority=True, slot_id=w2_sid)
        assert sem._rt_available == 1

