#!/usr/bin/env python3
"""Synchronize canonical Go internal helpers from a single source of truth.

Every Go service in Alt builds inside a service-scoped Docker build context
and CI sparse-checkout, so shared helpers cannot be imported across service
directories without breaking standalone builds. Instead, the canonical source
lives under ``scripts/codegen/go_canonical/`` and is deterministically copied
into each declared Go module's ``internal/`` tree with a standard Go generated
file header.

Usage:
    python3 scripts/codegen/sync_go_canonical.py          # write all targets
    python3 scripts/codegen/sync_go_canonical.py --check  # fail on drift
"""

from __future__ import annotations

import argparse
import difflib
import os
import pathlib
import sys
from dataclasses import dataclass

GENERATED_HEADER = "// Code generated by scripts/codegen/sync_go_canonical.py; DO NOT EDIT.\n\n"
HEADER_PREFIX = "// Code generated by scripts/codegen/sync_go_canonical.py; DO NOT EDIT."


@dataclass(frozen=True)
class CanonicalPackage:
    name: str
    files: tuple[str, ...]
    targets: tuple[str, ...]


PACKAGES: tuple[CanonicalPackage, ...] = (
    CanonicalPackage(
        name="httpserver",
        files=("httpserver_gen.go", "httpserver_gen_test.go"),
        targets=(
            "alt-backend/app",
            "alt-backend/sidecar-proxy",
            "alt-butterfly-facade",
            "alt-perf/k6/mock-rss-server",
            "auth-hub",
            "docker/inference-proxy",
            "docker/otel-relay",
            "docker/readonly-proxy",
            "knowledge-sovereign/app",
            "mq-hub/app",
            "pki-agent",
            "pre-processor-sidecar/app",
            "pre-processor/app",
            "rag-orchestrator",
            "search-indexer/app",
        ),
    ),
    CanonicalPackage(
        name="fsperm",
        files=("fsperm_gen.go",),
        targets=(
            "alt-backend/app",
            "alt-butterfly-facade",
            "altctl",
            "auth-hub",
            "knowledge-sovereign/app",
            "mq-hub/app",
            "pki-agent",
            "pre-processor/app",
            "proto/tools/protovis",
            "rag-orchestrator",
            "search-indexer/app",
        ),
    ),
    CanonicalPackage(
        name="connectguard",
        files=("connectguard_gen.go", "connectguard_gen_test.go"),
        targets=(
            "alt-backend/app",
            "pre-processor/app",
            "rag-orchestrator",
            "search-indexer/app",
        ),
    ),
)

SKIP_SCAN_DIRS = frozenset(
    {
        ".git",
        "node_modules",
        "stopped-using-k8s",
        "target",
        ".venv",
        "vendor",
    }
)


def default_repo_root() -> pathlib.Path:
    return pathlib.Path(__file__).resolve().parents[2]


def render_file(canonical_dir: pathlib.Path, pkg: CanonicalPackage, filename: str) -> str:
    src_path = canonical_dir / pkg.name / filename
    body = src_path.read_text(encoding="utf-8")
    if body.startswith(HEADER_PREFIX):
        return body
    return GENERATED_HEADER + body


def expected_outputs(
    repo_root: pathlib.Path,
    canonical_dir: pathlib.Path,
    packages: tuple[CanonicalPackage, ...] = PACKAGES,
) -> dict[pathlib.Path, str]:
    outputs: dict[pathlib.Path, str] = {}
    for pkg in packages:
        for filename in pkg.files:
            rendered = render_file(canonical_dir, pkg, filename)
            for target in pkg.targets:
                dest = repo_root / target / "internal" / pkg.name / filename
                outputs[dest] = rendered
    return outputs


def find_orphan_generated_files(
    repo_root: pathlib.Path,
    expected: set[pathlib.Path],
) -> list[pathlib.Path]:
    orphans: list[pathlib.Path] = []
    canonical_root = (repo_root / "scripts" / "codegen" / "go_canonical").resolve()
    for path in sorted(repo_root.rglob("*.go")):
        rel_parts = path.relative_to(repo_root).parts
        if any(part in SKIP_SCAN_DIRS for part in rel_parts):
            continue
        if path.resolve().is_relative_to(canonical_root):
            continue
        if path in expected:
            continue
        try:
            first_line = path.read_text(encoding="utf-8", errors="ignore").splitlines()[0]
        except (OSError, IndexError):
            continue
        if first_line.strip() == HEADER_PREFIX:
            orphans.append(path)
    return orphans


def sync(
    repo_root: pathlib.Path,
    *,
    check: bool,
    canonical_dir: pathlib.Path | None = None,
    packages: tuple[CanonicalPackage, ...] = PACKAGES,
) -> int:
    cdir = (
        canonical_dir
        if canonical_dir is not None
        else repo_root / "scripts" / "codegen" / "go_canonical"
    )
    outputs = expected_outputs(repo_root, cdir, packages)
    drifted: list[str] = []
    written = 0

    for dest, expected_content in sorted(outputs.items()):
        rel = dest.relative_to(repo_root).as_posix()
        current = dest.read_text(encoding="utf-8") if dest.is_file() else None
        if current == expected_content:
            continue
        if check:
            if current is None:
                drifted.append(f"MISSING: {rel}")
            else:
                diff = "".join(
                    difflib.unified_diff(
                        current.splitlines(keepends=True),
                        expected_content.splitlines(keepends=True),
                        fromfile=f"a/{rel}",
                        tofile=f"b/{rel}",
                        n=2,
                    )
                )
                drifted.append(f"DRIFT: {rel}\n{diff}")
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(expected_content, encoding="utf-8", newline="\n")
            written += 1

    orphans = find_orphan_generated_files(repo_root, set(outputs.keys()))
    for orphan in orphans:
        rel = orphan.relative_to(repo_root).as_posix()
        drifted.append(f"ORPHAN: {rel}")

    if check:
        if drifted:
            for item in drifted:
                sys.stderr.write(f"{item}\n")
            sys.stderr.write(
                f"ERROR: {len(drifted)} canonical Go file(s) out of sync. "
                "Run `python3 scripts/codegen/sync_go_canonical.py`.\n"
            )
            return 1
        sys.stdout.write(f"OK: {len(outputs)} canonical Go files are in sync.\n")
        return 0

    if orphans:
        for orphan in orphans:
            rel = orphan.relative_to(repo_root).as_posix()
            sys.stderr.write(f"WARNING: orphan generated file not in manifest: {rel}\n")
        return 1

    sys.stdout.write(f"Synced {written}/{len(outputs)} canonical Go files.\n")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify all generated files match canonical templates without writing.",
    )
    parser.add_argument(
        "--repo-root",
        type=pathlib.Path,
        default=None,
        help="Override repository root (used by unit tests).",
    )
    args = parser.parse_args(argv)
    repo_root = args.repo_root.resolve() if args.repo_root is not None else default_repo_root()
    return sync(repo_root, check=args.check)


if __name__ == "__main__":
    _launcher = (
        pathlib.Path(__file__).resolve().parents[2] / "scripts" / "altharness" / "alt-harness"
    )
    if _launcher.is_file():
        os.execv(_launcher, [str(_launcher), "sync-go", *sys.argv[1:]])  # noqa: S606 -- delegates CLI execution to the Go harness
    sys.exit(main())
