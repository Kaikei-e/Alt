#!/usr/bin/env python3
"""Generate and drift-check Python infra/pki packages from canonical templates.

Single source of truth for the 6 Python microservices that embed in-process
step-ca PKI enrollment (ARCH-04). Each service builds in Docker with an
isolated per-service build context, so generated modules are committed in
each service and verified for zero drift in CI via ``--check``.

Usage:
    python3 scripts/codegen/pki_py/sync_python_pki.py          # regenerate all 6
    python3 scripts/codegen/pki_py/sync_python_pki.py --check  # verify zero drift
"""

from __future__ import annotations

import argparse
import os
import pathlib
import sys
from dataclasses import dataclass
from typing import Literal

GENERATED_HEADER = "# Code generated by scripts/codegen/pki_py/sync_python_pki.py; DO NOT EDIT.\n"

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
TEMPLATES_DIR = SCRIPT_DIR / "templates"
DEFAULT_REPO_ROOT = SCRIPT_DIR.parents[2]

Flavor = Literal["thread", "asyncio"]
TlsGate = Literal["inbound_mtls", "outbound_mtls", "external"]


