#!/usr/bin/env python3
"""Tests for scripts/codegen/pki_py/sync_python_pki.py (ARCH-04).

Run:
    python3 scripts/tests/test-sync-python-pki.py
"""

from __future__ import annotations

import pathlib
import subprocess
import sys
import tempfile
import unittest

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
SYNC_SCRIPT = REPO_ROOT / "scripts" / "codegen" / "pki_py" / "sync_python_pki.py"
GENERATED_HEADER = "# Code generated by scripts/codegen/pki_py/sync_python_pki.py; DO NOT EDIT."

SERVICE_PKI_DIRS = (
    "news-creator/app/news_creator/infra/pki",
    "recap-subworker/recap_subworker/app/infra/pki",
    "tts-speaker/tts_speaker/infra/pki",
    "recap-evaluator/src/recap_evaluator/infra/pki",
    "acolyte-orchestrator/acolyte/infra/pki",
    "tag-generator/app/tag_generator/infra/pki",
)


def _run_sync(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(  # noqa: S603 - fixed local python invocation in test
        [sys.executable, str(SYNC_SCRIPT), *args],
        capture_output=True,
        text=True,
        check=False,
    )


class TestSyncPythonPki(unittest.TestCase):
    def test_check_exits_zero_on_current_repo(self) -> None:
        proc = _run_sync("--check")
        assert proc.returncode == 0, (
            f"sync_python_pki.py --check failed (rc={proc.returncode}):\n"
            f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
        )

    def test_every_generated_file_starts_with_generated_header(self) -> None:
        for rel_dir in SERVICE_PKI_DIRS:
            pki_dir = REPO_ROOT / rel_dir
            py_files = sorted(pki_dir.glob("*.py"))
            assert py_files, f"no generated .py files in {rel_dir}"
            for path in py_files:
                first_line = path.read_text(encoding="utf-8").splitlines()[0]
                assert first_line == GENERATED_HEADER, (
                    f"{path.relative_to(REPO_ROOT)} missing generated header: {first_line!r}"
                )

    def test_tampered_file_causes_check_to_fail_naming_drifted_file(self) -> None:
        with tempfile.TemporaryDirectory(prefix="alt-pki-sync-test-") as tmp:
            tmp_root = pathlib.Path(tmp)
            sync_proc = _run_sync("--repo-root", str(tmp_root))
            assert sync_proc.returncode == 0, sync_proc.stderr

            clean_proc = _run_sync("--repo-root", str(tmp_root), "--check")
            assert clean_proc.returncode == 0, clean_proc.stderr

            target = tmp_root / SERVICE_PKI_DIRS[0] / "ops.py"
            target.write_text(
                target.read_text(encoding="utf-8") + "\n# manual tamper\n",
                encoding="utf-8",
            )

            drift_proc = _run_sync("--repo-root", str(tmp_root), "--check")
            assert drift_proc.returncode == 1
            combined = drift_proc.stdout + drift_proc.stderr
            expected_rel = f"{SERVICE_PKI_DIRS[0]}/ops.py"
            assert expected_rel in combined, f"expected {expected_rel!r} in output:\n{combined}"

    def test_unexpected_extra_py_file_flagged_as_drift(self) -> None:
        with tempfile.TemporaryDirectory(prefix="alt-pki-sync-extra-") as tmp:
            tmp_root = pathlib.Path(tmp)
            sync_proc = _run_sync("--repo-root", str(tmp_root))
            assert sync_proc.returncode == 0, sync_proc.stderr

            extra = tmp_root / SERVICE_PKI_DIRS[-1] / "rogue_helper.py"
            extra.write_text("# unexpected manual file\n", encoding="utf-8")

            drift_proc = _run_sync("--repo-root", str(tmp_root), "--check")
            assert drift_proc.returncode == 1
            combined = drift_proc.stdout + drift_proc.stderr
            expected_rel = f"{SERVICE_PKI_DIRS[-1]}/rogue_helper.py"
            assert expected_rel in combined, f"expected {expected_rel!r} in output:\n{combined}"

    def test_missing_file_flagged_as_drift(self) -> None:
        with tempfile.TemporaryDirectory(prefix="alt-pki-sync-missing-") as tmp:
            tmp_root = pathlib.Path(tmp)
            sync_proc = _run_sync("--repo-root", str(tmp_root))
            assert sync_proc.returncode == 0, sync_proc.stderr

            missing = tmp_root / SERVICE_PKI_DIRS[1] / "state.py"
            missing.unlink()

            drift_proc = _run_sync("--repo-root", str(tmp_root), "--check")
            assert drift_proc.returncode == 1
            combined = drift_proc.stdout + drift_proc.stderr
            expected_rel = f"{SERVICE_PKI_DIRS[1]}/state.py"
            assert expected_rel in combined, f"expected {expected_rel!r} in output:\n{combined}"


if __name__ == "__main__":
    unittest.main()
