#!/usr/bin/env python3
"""Tests for scripts/lint/check_ratchet.py (CHECK-02).

Verifies:
1. Per-(target, kind) inline suppression counting across Python, Go, Rust, TS/Svelte/Deno,
   excluding generated/corpus/k8s paths and ignoring string literals.
2. Longest-prefix target resolution and repo-root fallback.
3. Ratchet enforcement: exact match passes; increase fails; decrease fails instructing --update.
4. --update regenerates suppressions.toml and preserves [governance] max_judgment_rules unless
   --max-judgment-rules is explicitly passed.
5. block-new rule fingerprint baseline (--findings-json / check-fingerprints / --update-fingerprints):
   existing fingerprinted violations pass across line shifts, new fingerprints fail, and removing
   an existing violation lowers the baseline on --update-fingerprints.
6. End-to-end verification against the real repository.

Run:
    python3 scripts/tests/test-check-ratchet.py
"""

from __future__ import annotations

import importlib.util
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import tomllib
import types
from unittest import mock

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "lint" / "check_ratchet.py"
SUPPRESSIONS_TOML = ROOT / "scripts" / "lint" / "ratchet" / "suppressions.toml"
RULE_BASELINES_TOML = ROOT / "scripts" / "lint" / "ratchet" / "rule_baselines.toml"
GIT_BIN = shutil.which("git")
assert GIT_BIN is not None, "git executable not found in PATH"
SAMPLE_MAX_JUDGMENT_RULES = 12


class _Results:
    def __init__(self) -> None:
        self.passed = 0
        self.failed = 0


RESULTS = _Results()


def check(name: str, condition: bool, detail: str = "") -> None:
    if condition:
        sys.stdout.write(f"  PASS  {name}\n")
        RESULTS.passed += 1
    else:
        suffix = f" ({detail})" if detail else ""
        sys.stdout.write(f"  FAIL  {name}{suffix}\n")
        RESULTS.failed += 1


def load_ratchet() -> types.ModuleType:
    if not SCRIPT.is_file():
        sys.stderr.write(f"FAIL: ratchet script missing: {SCRIPT}\n")
        sys.exit(1)
    spec = importlib.util.spec_from_file_location("check_ratchet", SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    with mock.patch.dict(sys.modules, {"check_ratchet": module}):
        spec.loader.exec_module(module)
    return module


def git_env() -> dict[str, str]:
    env = os.environ.copy()
    env.update(
        {
            "GIT_AUTHOR_NAME": "Test Author",
            "GIT_AUTHOR_EMAIL": "test@example.com",
            "GIT_COMMITTER_NAME": "Test Committer",
            "GIT_COMMITTER_EMAIL": "test@example.com",
        }
    )
    return env


def run_git(repo: pathlib.Path, *args: str) -> str:
    assert GIT_BIN is not None
    res = subprocess.run(  # noqa: S603 - fixed argv built in this test
        [GIT_BIN, "-C", str(repo), *args],
        env=git_env(),
        capture_output=True,
        text=True,
        check=True,
    )
    return res.stdout.strip()


def run_cli(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(  # noqa: S603 - fixed argv built in this test
        [sys.executable, str(SCRIPT), *args],
        capture_output=True,
        text=True,
        check=False,
    )


def _create_sample_repo(tmp: pathlib.Path) -> pathlib.Path:
    repo = tmp / "repo"
    repo.mkdir()
    run_git(repo, "init")

    # Python target
    py_dir = repo / "svc-py"
    py_dir.mkdir()
    (py_dir / "pyproject.toml").write_text('[project]\nname = "svc-py"\n', encoding="utf-8")
    (py_dir / "app.py").write_text(
        "a = 1  # noqa: F401 -- keep symbol\n"
        'b = "# noqa: S101"\n'
        "c = 2  # noqa: S603 -- fixed argv\n",
        encoding="utf-8",
    )

    # Nested Go target (tests longest prefix match)
    outer_go = repo / "svc-go"
    outer_go.mkdir()
    (outer_go / "go.mod").write_text("module example.com/outer\n", encoding="utf-8")
    (outer_go / "main.go").write_text(
        "package main\nfunc f() {\n"
        "    _ = a() // #nosec G304 -- trusted config path\n"
        "    _ = b() //nolint:noctx // test helper\n"
        '    _ = "//nolint:errcheck // #nosec G304"\n'
        "}\n",
        encoding="utf-8",
    )
    # Generated DO NOT EDIT file must be excluded
    (outer_go / "generated_client.go").write_text(
        "// Code generated by oapi-codegen DO NOT EDIT.\n"
        "package main\nfunc g() { _ = a() //nolint:errcheck // gen\n}\n",
        encoding="utf-8",
    )
    inner_go = outer_go / "cmd" / "tool"
    inner_go.mkdir(parents=True)
    (inner_go / "go.mod").write_text("module example.com/inner\n", encoding="utf-8")
    (inner_go / "tool.go").write_text(
        "package main\nfunc t() { _ = a() // #nosec G304 -- nested tool\n}\n",
        encoding="utf-8",
    )

    # Rust target
    rs_dir = repo / "svc-rs" / "src"
    rs_dir.mkdir(parents=True)
    (repo / "svc-rs" / "Cargo.toml").write_text('[package]\nname = "svc-rs"\n', encoding="utf-8")
    (rs_dir / "lib.rs").write_text(
        '#[allow(dead_code)]\nfn helper() { let _ = "#[allow(clippy::all)]"; }\n',
        encoding="utf-8",
    )

    # Frontend / TS & Deno targets
    ts_dir = repo / "web" / "src"
    ts_dir.mkdir(parents=True)
    (repo / "web" / "bun.lock").write_text("", encoding="utf-8")
    (ts_dir / "a.ts").write_text(
        "// biome-ignore lint/suspicious/noExplicitAny: legacy api\n"
        "const x: any = 1;\n"
        'const s = "// biome-ignore lint: string";\n',
        encoding="utf-8",
    )
    deno_dir = repo / "deno-svc"
    deno_dir.mkdir()
    (deno_dir / "deno.json").write_text("{}\n", encoding="utf-8")
    (deno_dir / "mod.ts").write_text(
        "// deno-lint-ignore no-explicit-any\nconst y: any = 2;\n",
        encoding="utf-8",
    )

    # Repo-root file outside any target directory
    (repo / "root_helper.py").write_text(
        "x = 1  # noqa: F401 -- root helper\n",
        encoding="utf-8",
    )

    # Excluded paths
    for excluded_rel, body in (
        ("stopped-using-k8s/old.py", "x = 1  # noqa: F401\n"),
        ("scripts/harness/corpus/C-99/after.py", "x = 1  # noqa: F401\n"),
        ("svc-go/foo.pb.go", "package main\n//nolint:errcheck\n"),
        ("svc-go/gen/x.py", "x = 1  # noqa: F401\n"),
    ):
        p = repo / excluded_rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8")

    run_git(repo, "add", ".")
    return repo


def test_counting_and_ratchet(mod: types.ModuleType) -> None:
    sys.stdout.write("suppression counting and ratchet enforcement\n")
    with tempfile.TemporaryDirectory() as tmp_str:
        repo = _create_sample_repo(pathlib.Path(tmp_str))
        sup_file = repo / "scripts" / "lint" / "ratchet" / "suppressions.toml"

        # 1. --update generates suppressions.toml with exact counts
        res = run_cli(
            "--repo-root",
            str(repo),
            "--suppressions-file",
            str(sup_file),
            "--update",
            "--max-judgment-rules",
            "12",
        )
        check("ratchet --update succeeds", res.returncode == 0, res.stdout + res.stderr)
        data = tomllib.loads(sup_file.read_text(encoding="utf-8"))
        targets = data.get("targets", {})
        check(
            "counts match all 6 kinds and longest target prefix + repo-root",
            targets
            == {
                "deno-svc": {"ts_deno_ignore": 1},
                "repo-root": {"python_noqa": 1},
                "svc-go": {"go_nolint": 1, "go_nosec": 1},
                "svc-go/cmd/tool": {"go_nosec": 1},
                "svc-py": {"python_noqa": 2},
                "svc-rs": {"rust_allow": 1},
                "web": {"ts_biome_ignore": 1},
            },
            repr(targets),
        )
        check(
            "governance.max_judgment_rules persisted",
            data.get("governance", {}).get("max_judgment_rules") == SAMPLE_MAX_JUDGMENT_RULES,
            repr(data.get("governance")),
        )

        # 2. Default check passes on exact match
        res_ok = run_cli("--repo-root", str(repo), "--suppressions-file", str(sup_file))
        check(
            "exact match passes with exit 0", res_ok.returncode == 0, res_ok.stdout + res_ok.stderr
        )

        # 3. Increase fails with exit 1 reporting (target, kind)
        py_app = repo / "svc-py" / "app.py"
        original_py = py_app.read_text(encoding="utf-8")
        py_app.write_text(original_py + "d = 3  # noqa: F401 -- extra\n", encoding="utf-8")
        res_inc = run_cli("--repo-root", str(repo), "--suppressions-file", str(sup_file))
        out_inc = res_inc.stdout + res_inc.stderr
        check(
            "increase fails with exit 1 and reports (svc-py, python_noqa)",
            res_inc.returncode == 1 and "svc-py" in out_inc and "python_noqa" in out_inc,
            f"rc={res_inc.returncode} out={out_inc}",
        )

        # 4. Decrease also fails instructing --update
        py_app.write_text("a = 1  # noqa: F401 -- keep symbol\n", encoding="utf-8")
        res_dec = run_cli("--repo-root", str(repo), "--suppressions-file", str(sup_file))
        out_dec = res_dec.stdout + res_dec.stderr
        check(
            "decrease fails with exit 1 instructing --update",
            res_dec.returncode == 1
            and "svc-py" in out_dec
            and "python_noqa" in out_dec
            and "--update" in out_dec,
            f"rc={res_dec.returncode} out={out_dec}",
        )

        # 5. --update lowers ceiling and preserves [governance] max_judgment_rules
        res_upd = run_cli(
            "--repo-root", str(repo), "--suppressions-file", str(sup_file), "--update"
        )
        check("second --update succeeds", res_upd.returncode == 0, res_upd.stdout + res_upd.stderr)
        data2 = tomllib.loads(sup_file.read_text(encoding="utf-8"))
        check(
            "ceiling lowered to 1 and governance.max_judgment_rules preserved",
            data2["targets"]["svc-py"]["python_noqa"] == 1
            and data2.get("governance", {}).get("max_judgment_rules") == SAMPLE_MAX_JUDGMENT_RULES,
            repr(data2),
        )
        check(
            "resolve_target helper callable",
            mod.resolve_target("svc-go/cmd/tool/x.go", ["svc-go", "svc-go/cmd/tool"])
            == "svc-go/cmd/tool",
        )


def test_rule_fingerprint_baseline() -> None:
    sys.stdout.write("block-new rule fingerprint baseline\n")
    with tempfile.TemporaryDirectory() as tmp_str:
        repo = pathlib.Path(tmp_str) / "repo"
        repo.mkdir()
        src = repo / "pkg" / "mod.py"
        src.parent.mkdir(parents=True)
        src.write_text(
            "def f() -> None:\n    raise ValueError('old violation')  \n    return\n",
            encoding="utf-8",
        )
        baselines = repo / "rule_baselines.toml"
        findings_path = repo / "findings.json"

        # Ruff-style JSON schema
        findings_path.write_text(
            json.dumps(
                [
                    {
                        "code": "TRY003",
                        "filename": str(src),
                        "location": {"row": 2, "column": 5},
                    }
                ]
            ),
            encoding="utf-8",
        )

        res_upd = run_cli(
            "check-fingerprints",
            "--repo-root",
            str(repo),
            "--baselines-file",
            str(baselines),
            "--findings-json",
            str(findings_path),
            "--update-fingerprints",
        )
        check(
            "--update-fingerprints creates baseline",
            res_upd.returncode == 0 and baselines.is_file(),
            res_upd.stdout + res_upd.stderr,
        )

        # Shift line down by 2 lines and vary whitespace -> still passes!
        src.write_text(
            "# shifted header\n\n"
            "def f() -> None:\n"
            "        raise   ValueError('old violation')\n"
            "    return\n",
            encoding="utf-8",
        )
        findings_path.write_text(
            json.dumps([{"rule": "TRY003", "file": "pkg/mod.py", "line": 4}]),
            encoding="utf-8",
        )
        res_shift = run_cli(
            "check-fingerprints",
            "--repo-root",
            str(repo),
            "--baselines-file",
            str(baselines),
            "--findings-json",
            str(findings_path),
        )
        check(
            "existing fingerprinted violation passes across line shift and whitespace change",
            res_shift.returncode == 0,
            res_shift.stdout + res_shift.stderr,
        )

        # Add a NEW violation -> must fail!
        src.write_text(
            "# shifted header\n\n"
            "def f() -> None:\n"
            "        raise   ValueError('old violation')\n"
            "    raise ValueError('brand new violation')\n",
            encoding="utf-8",
        )
        findings_path.write_text(
            json.dumps(
                [
                    {"rule": "TRY003", "file": "pkg/mod.py", "line": 4},
                    {"rule": "TRY003", "file": "pkg/mod.py", "line": 5},
                ]
            ),
            encoding="utf-8",
        )
        res_new = run_cli(
            "check-fingerprints",
            "--repo-root",
            str(repo),
            "--baselines-file",
            str(baselines),
            "--findings-json",
            str(findings_path),
        )
        out_new = res_new.stdout + res_new.stderr
        check(
            "new violation fingerprint fails with exit 1",
            res_new.returncode == 1 and "TRY003" in out_new and "pkg/mod.py" in out_new,
            f"rc={res_new.returncode} out={out_new}",
        )

        # Remove existing violation -> passes and --update-fingerprints lowers baseline
        findings_path.write_text("[]", encoding="utf-8")
        res_lower = run_cli(
            "--repo-root",
            str(repo),
            "--baselines-file",
            str(baselines),
            "--findings-json",
            str(findings_path),
            "--update-fingerprints",
        )
        check(
            "--update-fingerprints lowers baseline when violation removed",
            res_lower.returncode == 0,
            res_lower.stdout + res_lower.stderr,
        )
        bl_data = tomllib.loads(baselines.read_text(encoding="utf-8"))
        check(
            "baseline ledger now empty after removal",
            len(bl_data.get("fingerprints", [])) == 0,
            repr(bl_data),
        )

        # Re-introducing the previously removed violation now fails!
        findings_path.write_text(
            json.dumps([{"rule": "TRY003", "file": "pkg/mod.py", "line": 4}]),
            encoding="utf-8",
        )
        res_reintro = run_cli(
            "--repo-root",
            str(repo),
            "--baselines-file",
            str(baselines),
            "--findings-json",
            str(findings_path),
        )
        check(
            "re-introduced violation fails after baseline was lowered",
            res_reintro.returncode == 1,
            f"rc={res_reintro.returncode} out={res_reintro.stdout + res_reintro.stderr}",
        )


def test_real_repository() -> None:
    sys.stdout.write("real repository verification\n")
    check("suppressions.toml exists", SUPPRESSIONS_TOML.is_file(), str(SUPPRESSIONS_TOML))
    check("rule_baselines.toml exists", RULE_BASELINES_TOML.is_file(), str(RULE_BASELINES_TOML))
    if RULE_BASELINES_TOML.is_file():
        bl = tomllib.loads(RULE_BASELINES_TOML.read_text(encoding="utf-8"))
        check("rule_baselines.toml has version=1", bl.get("version") == 1, repr(bl))
    res = run_cli()
    check(
        "real repository passes check_ratchet.py with exit 0",
        res.returncode == 0,
        f"rc={res.returncode}\n{res.stdout}{res.stderr}",
    )


def main() -> int:
    mod = load_ratchet()
    test_counting_and_ratchet(mod)
    test_rule_fingerprint_baseline()
    test_real_repository()
    sys.stdout.write(f"\n{RESULTS.passed} passed, {RESULTS.failed} failed\n")
    return 1 if RESULTS.failed else 0


if __name__ == "__main__":
    sys.exit(main())
