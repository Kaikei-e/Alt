var bareKey = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)

func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"', '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\b':
			b.WriteString(`\b`)
		case '\f':
			b.WriteString(`\f`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 {
				fmt.Fprintf(&b, `\u%04x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

func tomlKey(k string) string {
	if bareKey.MatchString(k) {
		return k
	}
	return tomlString(k)
}

func renderSuppressions(counts map[string]map[string]int, gov map[string]any) string {
	lines := []string{
		"# Inline suppression count ratchet baseline (CHECK-02).",
		"# Auto-generated by `python3 scripts/lint/check_ratchet.py --update`.",
		"# Counts may only decrease; increasing any (target, kind) count fails CI.",
		"",
		"version = 1",
		"",
	}
	if len(gov) > 0 {
		lines = append(lines, "[governance]")
		keys := make([]string, 0, len(gov))
		for k := range gov {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			if frag, ok := renderGov(gov[k]); ok {
				lines = append(lines, tomlKey(k)+" = "+frag)
			}
		}
		lines = append(lines, "")
	}
	targets := make([]string, 0, len(counts))
	for t := range counts {
		targets = append(targets, t)
	}
	sort.Strings(targets)
	for _, target := range targets {
		kinds := counts[target]
		if len(kinds) == 0 {
			continue
		}
		ks := make([]string, 0, len(kinds))
		for k, n := range kinds {
			if n > 0 {
				ks = append(ks, k)
			}
		}
		if len(ks) == 0 {
			continue
		}
		sort.Strings(ks)
		lines = append(lines, "[targets."+tomlKey(target)+"]")
		for _, k := range ks {
			lines = append(lines, fmt.Sprintf("%s = %d", k, kinds[k]))
		}
		lines = append(lines, "")
	}
	return strings.Join(lines, "\n")
}

func renderGov(v any) (string, bool) {
	switch t := v.(type) {
	case bool:
		if t {
			return "true", true
		}
		return "false", true
	case int:
		return strconv.Itoa(t), true
	case int64:
		return strconv.FormatInt(t, 10), true
	case uint64:
		return strconv.FormatUint(t, 10), true
	case string:
		return tomlString(t), true
	case *big.Int:
		if t == nil {
			return "", false
		}
		return t.String(), true
	default:
		return "", false
	}
}

func renderBaselines(counts map[fpKey]int) string {
	lines := []string{
		"# block-new rule violation fingerprint baseline ledger (CHECK-02).",
		"# Managed by `python3 scripts/lint/check_ratchet.py --findings-json <file> --update-fingerprints`.",
		"# Existing fingerprinted violations pass; new fingerprints fail. Never use `ruff --add-noqa`.",
		"",
		"version = 1",
		"",
	}
	if len(counts) == 0 {
		lines = append(lines, "fingerprints = []", "")
		return strings.Join(lines, "\n")
	}
	keys := make([]fpKey, 0, len(counts))
	for k, n := range counts {
		if n > 0 {
			keys = append(keys, k)
		}
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].rule != keys[j].rule {
			return keys[i].rule < keys[j].rule
		}
		if keys[i].file != keys[j].file {
			return keys[i].file < keys[j].file
		}
		return keys[i].sha < keys[j].sha
	})
	if len(keys) == 0 {
		lines = append(lines, "fingerprints = []", "")
		return strings.Join(lines, "\n")
	}
	for _, k := range keys {
		lines = append(lines,
			"[[fingerprints]]",
			"rule = "+tomlString(k.rule),
			"file = "+tomlString(k.file),
			"line_sha256 = "+tomlString(k.sha),
			fmt.Sprintf("count = %d", counts[k]),
			"",
		)
	}
	return strings.Join(lines, "\n")
}

func tomlMaps(v any) ([]map[string]any, bool) {
	switch t := v.(type) {
	case []any:
		out := make([]map[string]any, 0, len(t))
		for _, item := range t {
			m, ok := item.(map[string]any)
			if !ok {
				continue
			}
			out = append(out, m)
		}
		return out, true
	case []map[string]any:
		return t, true
	default:
		return nil, false
	}
}

func loadTOML(path string) (map[string]any, error) {
	b, err := readOS(path)
	if err != nil {
		return nil, err
	}
	text, err := decodeUTF8Strict(b)
	if err != nil {
		return nil, err
	}
	var doc map[string]any
	if err := tomlx.Unmarshal([]byte(text), &doc); err != nil {
		return nil, err
	}
	if doc == nil {
		doc = map[string]any{}
	}
	return doc, nil
}

func positiveTOMLInt(v any) (int, bool) {
	switch n := v.(type) {
	case bool:
		if n {
			return 1, true
		}
		return 0, false
	case int64:
		if n > 0 {
			return int(n), true
		}
	case int:
		if n > 0 {
			return n, true
		}
	case uint64:
		if n > 0 {
			return int(n), true
		}
	}
	return 0, false
}

func loadSuppressions(path string) (map[string]map[string]int, map[string]any, error) {
	doc, err := loadTOML(path)
	if err != nil {
		return nil, nil, err
	}
	recorded := map[string]map[string]int{}
	if raw, ok := doc["targets"].(map[string]any); ok {
		for target, kinds := range raw {
			tbl, ok := kinds.(map[string]any)
			if !ok {
				continue
			}
			parsed := map[string]int{}
			for kind, val := range tbl {
				if n, ok := positiveTOMLInt(val); ok {
					parsed[kind] = n
				}
			}
			if len(parsed) > 0 {
				recorded[target] = parsed
			}
		}
	}
	gov := map[string]any{}
	if raw, ok := doc["governance"].(map[string]any); ok {
		for k, v := range raw {
			gov[k] = v
		}
	}
	return recorded, gov, nil
}

func loadBaselines(path string) (map[fpKey]int, error) {
	counts := map[fpKey]int{}
	if !isRegularFile(path) {
		return counts, nil
	}
	doc, err := loadTOML(path)
	if err != nil {
		return nil, err
	}
	entries, ok := tomlMaps(doc["fingerprints"])
	if !ok {
		return counts, nil
	}
	for _, entry := range entries {
		rule, rok := entry["rule"].(string)
		file, fok := entry["file"].(string)
		sha, sok := entry["line_sha256"].(string)
		count := 1
		if c, exists := entry["count"]; exists {
			n, ok := positiveTOMLInt(c)
			if !ok {
				continue
			}
			count = n
		}
		if rok && fok && sok && count > 0 {
			counts[fpKey{rule: rule, file: file, sha: sha}] += count
		}
	}
	return counts, nil
}

func writeFile(path, text string) error {
	if err := os.MkdirAll(filepath.Dir(path), fsperm.Dir); err != nil {
		return fmt.Errorf("%s", pyOSError(err))
	}
	if err := os.WriteFile(path, []byte(text), fsperm.File); err != nil {
		return fmt.Errorf("%s", pyOSError(err))
	}
	return nil
}
