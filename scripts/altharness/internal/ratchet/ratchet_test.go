func TestSuppressionCounts(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name string
		path string
		src  string
		want map[string]int
	}{
		{
			name: "python noqa and nosec ignore strings",
			path: "svc/app.py",
			src:  "a = 1  # noqa: S104 - reason  # nosec B104\nb = 2  # nosec B310\nc = \"# nosec B608\"\n",
			want: map[string]int{"python_noqa": 1, "python_nosec": 2},
		},
		{
			name: "file-level noqa is not inline",
			path: "svc/app.py",
			src:  "# ruff: noqa\nx = 1\n# flake8: noqa\n",
			want: nil,
		},
		{
			name: "go nolint and nosec ignore strings",
			path: "svc/main.go",
			src:  "package main\nfunc f() {\n    _ = a() // #nosec G304 -- trusted\n    _ = b() //nolint:noctx // helper\n    _ = \"//nolint:errcheck // #nosec G304\"\n}\n",
			want: map[string]int{"go_nolint": 1, "go_nosec": 1},
		},
		{
			name: "generated go is excluded",
			path: "svc/gen.go",
			src:  "// Code generated by oapi-codegen DO NOT EDIT.\npackage main\n//nolint:errcheck\n",
			want: nil,
		},
		{
			name: "pb go path excluded",
			path: "svc/foo.pb.go",
			src:  "package main\n//nolint:errcheck\n",
			want: nil,
		},
		{
			name: "spaced rust allow and expect",
			path: "svc/src/lib.rs",
			src: "#![allow(clippy::all)]\n" +
				"#! [allow(dead_code)]\n" +
				"# [allow(unused)]\n" +
				"#[expect(dead_code)]\n" +
				"#![expect(clippy::pedantic)]\n" +
				"#! [expect(unused_variables)]\n" +
				"let s = \"# [allow(dead_code)] #[expect(dead_code)]\";\n",
			want: map[string]int{"rust_allow": 6},
		},
		{
			name: "biome ignores strings and ignore-all",
			path: "web/a.ts",
			src:  "// biome-ignore lint/suspicious/noExplicitAny: legacy\nconst x: any = 1;\nconst s = \"// biome-ignore lint: string\";\n// biome-ignore-all lint/style: file\n",
			want: map[string]int{"ts_biome_ignore": 1},
		},
		{
			name: "deno ignore but not file",
			path: "deno/mod.ts",
			src:  "// deno-lint-ignore no-explicit-any\nconst y: any = 2;\n// deno-lint-ignore-file no-explicit-any\n",
			want: map[string]int{"ts_deno_ignore": 1},
		},
		{
			name: "svelte html comment",
			path: "web/a.svelte",
			src:  "<script>\n  // biome-ignore lint/style: x\n</script>\n<!-- biome-ignore lint/a11y: y -->\n<div>{`// biome-ignore`}</div>\n",
			want: map[string]int{"ts_biome_ignore": 2},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got := countFileSuppressions(tc.path, tc.src)
			if !sameCounts(got, tc.want) {
				t.Fatalf("got %#v want %#v", got, tc.want)
			}
		})
	}
}

