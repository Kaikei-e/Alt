func TestResolveTautoBinPrecedence(t *testing.T) {
	t.Run("TAUTO_BIN overrides HOME and PATH", func(t *testing.T) {
		home := t.TempDir()
		localBin := filepath.Join(home, ".local", "bin", "tauto")
		if err := os.MkdirAll(filepath.Dir(localBin), fsperm.Dir); err != nil {
			t.Fatal(err)
		}
		if err := fsperm.WriteExecutable(localBin, []byte("#!/bin/sh\necho local\n")); err != nil {
			t.Fatal(err)
		}
		override := filepath.Join(t.TempDir(), "custom-tauto")
		if err := fsperm.WriteExecutable(override, []byte("#!/bin/sh\necho override\n")); err != nil {
			t.Fatal(err)
		}
		t.Setenv("HOME", home)
		t.Setenv("TAUTO_BIN", override)
		got, err := resolveTautoBin()
		if err != nil || got != override {
			t.Fatalf("got=%q err=%v want %q", got, err, override)
		}
	})

	t.Run("invalid TAUTO_BIN fails closed", func(t *testing.T) {
		t.Setenv("HOME", t.TempDir())
		t.Setenv("TAUTO_BIN", filepath.Join(t.TempDir(), "does-not-exist"))
		if _, err := resolveTautoBin(); err == nil {
			t.Fatal("expected error for invalid TAUTO_BIN")
		}
	})

	t.Run("HOME/.local/bin/tauto wins over cargo/bin on PATH", func(t *testing.T) {
		home := t.TempDir()
		localBin := filepath.Join(home, ".local", "bin", "tauto")
		cargoDir := filepath.Join(home, ".cargo", "bin")
		cargoBin := filepath.Join(cargoDir, "tauto")
		if err := os.MkdirAll(filepath.Dir(localBin), fsperm.Dir); err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(cargoDir, fsperm.Dir); err != nil {
			t.Fatal(err)
		}
		if err := fsperm.WriteExecutable(localBin, []byte("#!/bin/sh\necho local\n")); err != nil {
			t.Fatal(err)
		}
		if err := fsperm.WriteExecutable(cargoBin, []byte("#!/bin/sh\necho cargo\n")); err != nil {
			t.Fatal(err)
		}
		t.Setenv("HOME", home)
		t.Setenv("TAUTO_BIN", "")
		t.Setenv("PATH", cargoDir)
		got, err := resolveTautoBin()
		if err != nil || got != localBin {
			t.Fatalf("got=%q err=%v want %q", got, err, localBin)
		}
	})
}

