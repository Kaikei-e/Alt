func TestParseTautoPackageName(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name    string
		input   string
		want    string
		wantErr bool
	}{
		{
			name:  "standard block",
			input: "// comment\npackage {\n  name = \"hybrid-priority-semaphore\"\n  version = \"0.1.0\"\n}\n",
			want:  "hybrid-priority-semaphore",
		},
		{
			name:  "block ignores other sections",
			input: "dependencies {\n  foo { name = \"wrong\" }\n}\npackage {\n  version = \"0.1.0\"\n  name = \"sovereign-projection\"\n}\n",
			want:  "sovereign-projection",
		},
		{
			name:  "at-package section",
			input: "@package\nname = \"demo-tote\"\nversion = \"0.1.0\"\n@dependencies\nname = \"other\"\n",
			want:  "demo-tote",
		},
		{
			name:  "dotted key",
			input: "package.name = \"dotted-tote\"\npackage.version = \"0.1.0\"\n",
			want:  "dotted-tote",
		},
		{
			name:    "missing package name",
			input:   "package {\n  version = \"0.1.0\"\n}\n",
			wantErr: true,
		},
		{
			name:    "only commented out name",
			input:   "package {\n  // name = \"fake\"\n  version = \"0.1.0\"\n}\n",
			wantErr: true,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := parseTautoPackageName(tc.input)
			if tc.wantErr {
				if err == nil {
					t.Fatalf("expected error, got %q", got)
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if got != tc.want {
				t.Fatalf("got %q, want %q", got, tc.want)
			}
		})
	}
}

