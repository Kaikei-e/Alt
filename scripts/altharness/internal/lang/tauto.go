const tautoVersion = "0.1.0"

var (
	toteNameRE          = regexp.MustCompile(`^[a-z][a-z0-9-]*$`)
	eurePackageNameRE   = regexp.MustCompile(`^\s*name\s*=\s*"([^"]*)"`)
	eureDottedPkgNameRE = regexp.MustCompile(`^\s*package\.name\s*=\s*"([^"]*)"`)
	tautoVectorHeaderRE = regexp.MustCompile(`^# Code generated by tauto (\S+) from (specs/tauto/[a-z][a-z0-9-]+); DO NOT EDIT\.$`)
)

var tautoWalkExcludedDirs = map[string]struct{}{
	".git":              {},
	".tauto":            {},
	".venv":             {},
	"__pycache__":       {},
	"_reports":          {},
	"build":             {},
	"dist":              {},
	"node_modules":      {},
	"stopped-using-k8s": {},
	"target":            {},
	"vendor":            {},
}

type tautoTote struct {
	name     string
	dir      string
	srcFiles []string
	allFiles []string
	emitFile string
}

type tautoProofStatus struct {
	Files      int   `json:"files"`
	OK         int   `json:"ok"`
	Incomplete int   `json:"incomplete"`
	Holes      int   `json:"holes"`
	Failed     int   `json:"failed"`
	Skipped    int   `json:"skipped"`
	Axioms     []any `json:"axioms"`
	Externs    int   `json:"externs"`
	Unread     []any `json:"unread"`
}

// RunTauto is scripts/lint/tauto.sh. It enforces fail-fast Tauto version,
// canary audit, tote discovery, formatting, linting, proof checking,
// zero-axiom/zero-hole proof status, and golden vector parity.
func RunTauto(ctx context.Context, args []string, stdout, stderr io.Writer) int {
	ctx, stdout, stderr, code := prepare(ctx, stdout, stderr)
	if code != 0 {
		return code
	}
	if len(args) > 1 || (len(args) == 1 && args[0] != "tauto") {
		fmt.Fprintln(stderr, "usage: tauto.sh [tauto]")
		return 2
	}
	root, rc := mustRepo(stderr)
	if rc != 0 {
		return rc
	}
	if rc := canceled(ctx, stderr); rc != 0 {
		return rc
	}

	tautoBin, err := resolveTautoBin()
	if err != nil {
		fmt.Fprintf(stderr, "ERROR: %s\n", err.Error())
		return 1
	}
	verOut, verErr, verCode, verRunErr := capture(ctx, root, nil, tautoBin, "--version")
	if verRunErr != nil || verCode != 0 {
		fmt.Fprintf(stderr, "error: failed to run 'tauto --version': %s\n", strings.TrimSpace(verOut+verErr))
		return 1
	}
	expectedVer := "tauto " + tautoVersion
	actualVer := strings.TrimSpace(verOut)
	if actualVer != expectedVer {
		fmt.Fprintf(stderr, "error: tauto version mismatch: expected %q, got %q (%s)\n", expectedVer, actualVer, tautoBin)
		return 1
	}

	fmt.Fprintln(stdout, "==> [tauto] canary audit (tauto-canary)")
	if canary.RunAudit(ctx, []string{"tauto-canary", "--tauto-bin", tautoBin}, stdout, stderr) != 0 {
		return 1
	}

	totes, err := discoverTautoTotes(root)
	if err != nil {
		fmt.Fprintf(stderr, "error: %s\n", err.Error())
		return 1
	}

	for _, tote := range totes {
		if rc := canceled(ctx, stderr); rc != 0 {
			return rc
		}
		if err := verifyTautoTote(ctx, root, tautoBin, tote, stdout, stderr); err != nil {
			fmt.Fprintf(stderr, "error: [tauto/%s] %s\n", tote.name, err.Error())
			return 1
		}
	}

	fmt.Fprintf(stdout, "PASS: tauto (%d tote(s) verified)\n", len(totes))
	return 0
}

// resolveTautoBin locates the pinned tauto executable with deterministic
// precedence:
//  1. Explicit TAUTO_BIN environment override (fail-closed if unusable).
//  2. $HOME/.local/bin/tauto (make install-tauto destination), ahead of PATH
//     so a pinned install beats any stale ~/.cargo/bin/tauto on PATH.
//  3. tauto resolved via PATH.
func resolveTautoBin() (string, error) {
	if override := strings.TrimSpace(os.Getenv("TAUTO_BIN")); override != "" {
		resolved, err := exec.LookPath(override)
		if err != nil {
			return "", fmt.Errorf("TAUTO_BIN %q is not executable or not found: %w", override, err)
		}
		return resolved, nil
	}
	if home, err := os.UserHomeDir(); err == nil && home != "" {
		localBin := filepath.Join(home, ".local", "bin", "tauto")
		if info, statErr := os.Stat(localBin); statErr == nil && info.Mode().IsRegular() && info.Mode().Perm()&0o111 != 0 {
			return localBin, nil
		}
	}
	found, err := exec.LookPath("tauto")
	if err != nil {
		return "", errors.New("required command not found in PATH: tauto (install via `make install-tauto`)")
	}
	return found, nil
}

func discoverTautoTotes(root string) ([]tautoTote, error) {
	specsDir := filepath.Join(root, "specs", "tauto")
	if err := ensureWithinRepo(root, specsDir); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, errors.New("no Tauto totes found under specs/tauto/*/Tauto.eure")
		}
		return nil, err
	}
	st, err := os.Stat(specsDir)
	if err != nil || !st.IsDir() {
		return nil, errors.New("no Tauto totes found under specs/tauto/*/Tauto.eure")
	}
	entries, err := os.ReadDir(specsDir)
	if err != nil {
		return nil, fmt.Errorf("read specs/tauto: %w", err)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })

	var totes []tautoTote
	for _, entry := range entries {
		name := entry.Name()
		toteDir := filepath.Join(specsDir, name)
		manifestPath := filepath.Join(toteDir, "Tauto.eure")
		if _, statErr := os.Lstat(manifestPath); statErr != nil {
			continue
		}
		if err := ensureWithinRepo(root, toteDir); err != nil {
			return nil, fmt.Errorf("tote %s: %w", name, err)
		}
		if err := ensureWithinRepo(root, manifestPath); err != nil {
			return nil, fmt.Errorf("tote %s manifest: %w", name, err)
		}
		if !toteNameRE.MatchString(name) {
			return nil, fmt.Errorf("invalid tote directory name %q (must match %s)", name, toteNameRE.String())
		}
		manifestBytes, err := os.ReadFile(manifestPath)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", manifestPath, err)
		}
		pkgName, err := parseTautoPackageName(string(manifestBytes))
		if err != nil {
			return nil, fmt.Errorf("tote %s Tauto.eure: %w", name, err)
		}
		if pkgName != name {
			return nil, fmt.Errorf("tote %s package.name mismatch: Tauto.eure declares %q, expected %q", name, pkgName, name)
		}

		srcDir := filepath.Join(toteDir, "src")
		srcFiles, err := collectTautFiles(root, srcDir)
		if err != nil {
			return nil, fmt.Errorf("tote %s src/: %w", name, err)
		}
		if len(srcFiles) == 0 {
			return nil, fmt.Errorf("tote %s has no .taut files under specs/tauto/%s/src", name, name)
		}

		allFiles := append([]string{}, srcFiles...)
		vectorsDir := filepath.Join(toteDir, "vectors")
		var emitFile string
		if _, vErr := os.Lstat(vectorsDir); vErr == nil {
			vecFiles, err := collectTautFiles(root, vectorsDir)
			if err != nil {
				return nil, fmt.Errorf("tote %s vectors/: %w", name, err)
			}
			allFiles = append(allFiles, vecFiles...)
			candidateEmit := filepath.Join(vectorsDir, "emit.taut")
			if _, eErr := os.Lstat(candidateEmit); eErr == nil {
				if err := ensureWithinRepo(root, candidateEmit); err != nil {
					return nil, fmt.Errorf("tote %s vectors/emit.taut: %w", name, err)
				}
				emitFile = candidateEmit
			}
		}
		sort.Strings(allFiles)
		totes = append(totes, tautoTote{
			name:     name,
			dir:      toteDir,
			srcFiles: srcFiles,
			allFiles: allFiles,
			emitFile: emitFile,
		})
	}
	if len(totes) == 0 {
		return nil, errors.New("no Tauto totes found under specs/tauto/*/Tauto.eure")
	}
	return totes, nil
}

func verifyTautoTote(ctx context.Context, root, tautoBin string, tote tautoTote, stdout, stderr io.Writer) error {
	fmt.Fprintf(stdout, "==> [tauto/%s] fmt --check (%d files)\n", tote.name, len(tote.allFiles))
	fmtArgs := append([]string{tautoBin, "fmt", "--check"}, tote.allFiles...)
	if code, err := run(ctx, stdout, stderr, root, nil, fmtArgs...); err != nil || code != 0 {
		return fmt.Errorf("tauto fmt --check failed (exit %d)", code)
	}

	fmt.Fprintf(stdout, "==> [tauto/%s] lint --json\n", tote.name)
	lintOut, lintErr, lintCode, lintRunErr := capture(ctx, root, nil, tautoBin, "lint", "--json", tote.dir)
	if lintRunErr != nil || lintCode != 0 {
		return fmt.Errorf("tauto lint --json failed (exit %d): %s", lintCode, strings.TrimSpace(lintOut+"\n"+lintErr))
	}
	var diags []any
	if err := json.Unmarshal([]byte(strings.TrimSpace(lintOut)), &diags); err != nil {
		return fmt.Errorf("tauto lint --json returned invalid JSON: %w (stdout: %s)", err, strings.TrimSpace(lintOut))
	}
	if len(diags) != 0 {
		return fmt.Errorf("tauto lint --json reported %d diagnostic(s): %s", len(diags), strings.TrimSpace(lintOut))
	}

	fmt.Fprintf(stdout, "==> [tauto/%s] check --summary --timeout 60\n", tote.name)
	if code, err := run(ctx, stdout, stderr, root, nil, tautoBin, "--offline", "check", "--summary", "--timeout", "60", tote.dir); err != nil || code != 0 {
		return fmt.Errorf("tauto --offline check failed (exit %d)", code)
	}

	fmt.Fprintf(stdout, "==> [tauto/%s] proof-status --json\n", tote.name)
	srcDir := filepath.Join(tote.dir, "src")
	psOut, psErr, psCode, psRunErr := capture(ctx, root, nil, tautoBin, "--offline", "proof-status", "--json", srcDir)
	if psRunErr != nil || psCode != 0 {
		return fmt.Errorf("tauto --offline proof-status --json failed (exit %d): %s", psCode, strings.TrimSpace(psOut+"\n"+psErr))
	}
	if err := validateProofStatusJSON(psOut); err != nil {
		return fmt.Errorf("proof-status gate failed: %w", err)
	}

	if tote.emitFile != "" {
		fmt.Fprintf(stdout, "==> [tauto/%s] golden vector parity\n", tote.name)
		if err := verifyTautoGoldenVectors(ctx, root, tautoBin, tote, stdout, stderr); err != nil {
			return err
		}
	}
	return nil
}

func validateProofStatusJSON(raw string) error {
	trimmed := strings.TrimSpace(raw)
	var fields map[string]json.RawMessage
	if err := json.Unmarshal([]byte(trimmed), &fields); err != nil {
		return fmt.Errorf("invalid proof-status JSON: %w", err)
	}
	for _, req := range []string{"files", "ok", "incomplete", "holes", "failed", "skipped", "axioms", "externs", "unread"} {
		if _, exists := fields[req]; !exists {
			return fmt.Errorf("proof-status JSON missing required key %q", req)
		}
	}
	var ps tautoProofStatus
	if err := json.Unmarshal([]byte(trimmed), &ps); err != nil {
		return fmt.Errorf("decode proof-status JSON: %w", err)
	}
	if ps.Files <= 0 || ps.OK <= 0 || ps.Failed != 0 || ps.Holes != 0 || ps.Incomplete != 0 || ps.Skipped != 0 || len(ps.Axioms) != 0 || ps.Externs != 0 || len(ps.Unread) != 0 {
		return fmt.Errorf(
			"proof-status invariant violated (files=%d ok=%d failed=%d holes=%d incomplete=%d skipped=%d axioms=%v externs=%d unread=%v)",
			ps.Files, ps.OK, ps.Failed, ps.Holes, ps.Incomplete, ps.Skipped, ps.Axioms, ps.Externs, ps.Unread,
		)
	}
	return nil
}

func verifyTautoGoldenVectors(ctx context.Context, root, tautoBin string, tote tautoTote, stdout, stderr io.Writer) error {
	expectedSpec := "specs/tauto/" + tote.name
	expectedHeader := fmt.Sprintf("# Code generated by tauto %s from %s; DO NOT EDIT.", tautoVersion, expectedSpec)

	vectorFiles, err := findTautoVectorFiles(root, expectedSpec)
	if err != nil {
		return err
	}
	if len(vectorFiles) == 0 {
		return fmt.Errorf("no committed golden vector file found for %s (expected */testdata/*_vectors.txt starting with %q)", expectedSpec, expectedHeader)
	}

	runOut, runErr, runCode, execErr := capture(ctx, root, nil, tautoBin, "--offline", "run", tote.emitFile)
	if execErr != nil || runCode != 0 {
		return fmt.Errorf("tauto --offline run %s failed (exit %d): %s", tote.emitFile, runCode, strings.TrimSpace(runOut+"\n"+runErr))
	}
	expected := []byte(expectedHeader + "\n" + runOut)

	drifted := false
	for _, absPath := range vectorFiles {
		actual, err := os.ReadFile(absPath)
		if err != nil {
			return fmt.Errorf("read vector file %s: %w", absPath, err)
		}
		if bytes.Equal(actual, expected) {
			continue
		}
		drifted = true
		rel, relErr := filepath.Rel(root, absPath)
		if relErr != nil {
			rel = absPath
		}
		rel = filepath.ToSlash(rel)
		writeUnifiedDiff(ctx, root, rel, actual, expected, stdout, stderr)
	}
	if drifted {
		return fmt.Errorf("golden vector drift detected for %s; regenerate with `make tauto-vectors`", expectedSpec)
	}
	return nil
}

func findTautoVectorFiles(root, expectedSpec string) ([]string, error) {
	var matched []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if p == root {
			return nil
		}
		if d.IsDir() {
			if _, skip := tautoWalkExcludedDirs[d.Name()]; skip {
				return filepath.SkipDir
			}
			if d.Type()&os.ModeSymlink != 0 {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(d.Name(), "_vectors.txt") || filepath.Base(filepath.Dir(p)) != "testdata" {
			return nil
		}
		if err := ensureWithinRepo(root, p); err != nil {
			return err
		}
		firstLine, err := readFirstLine(p)
		if err != nil {
			return err
		}
		m := tautoVectorHeaderRE.FindStringSubmatch(firstLine)
		if m != nil && m[2] == expectedSpec {
			matched = append(matched, p)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(matched)
	return matched, nil
}

func readFirstLine(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer func() { _ = f.Close() }()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 4096), 1024*1024)
	if !sc.Scan() {
		return "", sc.Err()
	}
	return strings.TrimRight(sc.Text(), "\r"), nil
}

func writeUnifiedDiff(ctx context.Context, root, rel string, actual, expected []byte, stdout, stderr io.Writer) {
	if _, err := exec.LookPath("diff"); err == nil {
		tmpDir, err := os.MkdirTemp("", "alt-tauto-diff-")
		if err == nil {
			defer func() { _ = os.RemoveAll(tmpDir) }()
			aPath := filepath.Join(tmpDir, "committed")
			bPath := filepath.Join(tmpDir, "expected")
			if os.WriteFile(aPath, actual, fsperm.File) == nil && os.WriteFile(bPath, expected, fsperm.File) == nil {
				_, _ = run(ctx, stdout, stderr, root, nil, "diff", "-u", "--label", "a/"+rel, "--label", "b/"+rel, aPath, bPath)
				return
			}
		}
	}
	fmt.Fprintf(stdout, "--- a/%s\n+++ b/%s\n", rel, rel)
	aLines := strings.Split(strings.TrimSuffix(string(actual), "\n"), "\n")
	bLines := strings.Split(strings.TrimSuffix(string(expected), "\n"), "\n")
	maxLen := len(aLines)
	if len(bLines) > maxLen {
		maxLen = len(bLines)
	}
	for i := 0; i < maxLen; i++ {
		var aLine, bLine string
		hasA := i < len(aLines)
		hasB := i < len(bLines)
		if hasA {
			aLine = aLines[i]
		}
		if hasB {
			bLine = bLines[i]
		}
		if hasA && hasB && aLine == bLine {
			fmt.Fprintf(stdout, " %s\n", aLine)
			continue
		}
		if hasA {
			fmt.Fprintf(stdout, "-%s\n", aLine)
		}
		if hasB {
			fmt.Fprintf(stdout, "+%s\n", bLine)
		}
	}
}

func collectTautFiles(root, dir string) ([]string, error) {
	if err := ensureWithinRepo(root, dir); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	st, err := os.Stat(dir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	if !st.IsDir() {
		return nil, nil
	}
	var files []string
	err = filepath.WalkDir(dir, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if p != dir {
			if err := ensureWithinRepo(root, p); err != nil {
				return err
			}
		}
		if d.IsDir() {
			if d.Name() == ".tauto" {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(d.Name(), ".taut") {
			files = append(files, p)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	return files, nil
}

func ensureWithinRepo(root, target string) error {
	info, err := os.Lstat(target)
	if err != nil {
		return err
	}
	resolvedRoot, err := filepath.EvalSymlinks(root)
	if err != nil {
		resolvedRoot = filepath.Clean(root)
	}
	resolvedTarget, err := filepath.EvalSymlinks(target)
	if err != nil {
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("broken or escaping symlink %s: %w", target, err)
		}
		return err
	}
	rel, err := filepath.Rel(resolvedRoot, resolvedTarget)
	if err != nil {
		return fmt.Errorf("symlink escapes repository root: %s", target)
	}
	if rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return fmt.Errorf("symlink escapes repository root: %s -> %s", target, resolvedTarget)
	}
	return nil
}

// parseTautoPackageName extracts `package.name` from a Tauto.eure manifest,
// supporting `package { name = "..." }`, `@package\nname = "..."`, and
// `package.name = "..."` while ignoring comments and non-package sections.
func parseTautoPackageName(raw string) (string, error) {
	inPackageBlock := false
	inAtPackage := false
	blockDepth := 0
	packageBlockDepth := 0

	for _, rawLine := range strings.Split(strings.ReplaceAll(raw, "\r\n", "\n"), "\n") {
		line := strings.TrimSpace(stripEureLineComment(rawLine))
		if line == "" {
			continue
		}
		if m := eureDottedPkgNameRE.FindStringSubmatch(line); m != nil && blockDepth == 0 {
			if strings.TrimSpace(m[1]) == "" {
				return "", errors.New("package.name is empty")
			}
			return m[1], nil
		}
		if blockDepth == 0 && strings.HasPrefix(line, "@") {
			section := strings.TrimSpace(strings.TrimPrefix(line, "@"))
			inAtPackage = section == "package"
			continue
		}
		if inAtPackage && blockDepth == 0 {
			if m := eurePackageNameRE.FindStringSubmatch(line); m != nil {
				if strings.TrimSpace(m[1]) == "" {
					return "", errors.New("package.name is empty")
				}
				return m[1], nil
			}
		}
		opens, closes := countBracesOutsideQuotes(line)
		if !inPackageBlock && blockDepth == 0 && isPackageBlockStart(line) {
			inPackageBlock = true
			packageBlockDepth = blockDepth + opens - closes
			blockDepth += opens - closes
			if packageBlockDepth <= 0 {
				inPackageBlock = false
			}
			continue
		}
		if inPackageBlock && blockDepth == packageBlockDepth {
			if m := eurePackageNameRE.FindStringSubmatch(line); m != nil {
				if strings.TrimSpace(m[1]) == "" {
					return "", errors.New("package.name is empty")
				}
				return m[1], nil
			}
		}
		blockDepth += opens - closes
		if blockDepth < 0 {
			blockDepth = 0
		}
		if inPackageBlock && blockDepth < packageBlockDepth {
			inPackageBlock = false
		}
	}
	return "", errors.New("missing package.name in Tauto.eure")
}

func isPackageBlockStart(line string) bool {
	if !strings.HasPrefix(line, "package") {
		return false
	}
	rest := strings.TrimSpace(strings.TrimPrefix(line, "package"))
	return strings.HasPrefix(rest, "{")
}

func stripEureLineComment(line string) string {
	inQuote := false
	escaped := false
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if inQuote {
			if escaped {
				escaped = false
				continue
			}
			if ch == '\\' {
				escaped = true
				continue
			}
			if ch == '"' {
				inQuote = false
			}
			continue
		}
		if ch == '"' {
			inQuote = true
			continue
		}
		if ch == '/' && i+1 < len(line) && line[i+1] == '/' {
			return line[:i]
		}
	}
	return line
}

func countBracesOutsideQuotes(line string) (int, int) {
	inQuote := false
	escaped := false
	opens, closes := 0, 0
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if inQuote {
			if escaped {
				escaped = false
				continue
			}
			if ch == '\\' {
				escaped = true
				continue
			}
			if ch == '"' {
				inQuote = false
			}
			continue
		}
		switch ch {
		case '"':
			inQuote = true
		case '{':
			opens++
		case '}':
			closes++
		}
	}
	return opens, closes
}
