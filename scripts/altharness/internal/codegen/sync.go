var skipScanDirs = map[string]struct{}{
	".git": {}, "node_modules": {}, "stopped-using-k8s": {}, "target": {}, ".venv": {}, "vendor": {},
}

// Run is the CLI for `sync_go_canonical.py`.
func Run(ctx context.Context, args []string, stdout, stderr io.Writer) int {
	check := false
	repo := ""
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--check":
			check = true
		case "--repo-root":
			if i+1 >= len(args) || args[i+1] == "" {
				fmt.Fprintln(stderr, "ERROR: --repo-root requires a value")
				return 2
			}
			i++
			repo = args[i]
		case "-h", "--help":
			fmt.Fprintln(stdout, "usage: sync-go [--check] [--repo-root dir]")
			return 0
		default:
			fmt.Fprintf(stderr, "ERROR: unknown argument %q\n", args[i])
			return 2
		}
	}
	if repo == "" {
		repo = findRepoRoot()
	}
	abs, err := filepath.Abs(repo)
	if err != nil {
		fmt.Fprintf(stderr, "ERROR: %v\n", err)
		return 2
	}
	return Sync(ctx, abs, check, stdout, stderr)
}

// Sync checks or writes canonical Go copies. It returns 0, 1, or 2.
func Sync(ctx context.Context, repoRoot string, check bool, stdout, stderr io.Writer) int {
	if ctx == nil {
		fmt.Fprintln(stderr, "ERROR: nil context")
		return 2
	}
	canonical := filepath.Join(repoRoot, "scripts", "codegen", "go_canonical")
	outputs, err := expectedOutputs(repoRoot, canonical, Packages)
	if err != nil {
		fmt.Fprintf(stderr, "ERROR: %v\n", err)
		return 1
	}
	var drifted []string
	written := 0
	dests := make([]string, 0, len(outputs))
	for dest := range outputs {
		dests = append(dests, dest)
	}
	sort.Strings(dests)
	for _, dest := range dests {
		if ctx.Err() != nil {
			fmt.Fprintf(stderr, "ERROR: %v\n", ctx.Err())
			return 1
		}
		expected := outputs[dest]
		rel, err := filepath.Rel(repoRoot, dest)
		if err != nil {
			fmt.Fprintf(stderr, "ERROR: %v\n", err)
			return 1
		}
		rel = filepath.ToSlash(rel)
		current, readErr := os.ReadFile(dest)
		match := readErr == nil && string(current) == expected
		if match {
			continue
		}
		if check {
			if readErr != nil {
				drifted = append(drifted, "MISSING: "+rel)
			} else {
				drifted = append(drifted, "DRIFT: "+rel+"\n"+unifiedDiff(rel, current, []byte(expected)))
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(dest), fsperm.Dir); err != nil {
			fmt.Fprintf(stderr, "ERROR: %v\n", err)
			return 1
		}
		if err := os.WriteFile(dest, []byte(expected), fsperm.File); err != nil {
			fmt.Fprintf(stderr, "ERROR: %v\n", err)
			return 1
		}
		written++
	}
	expectedSet := map[string]struct{}{}
	for dest := range outputs {
		expectedSet[dest] = struct{}{}
	}
	orphans, err := findOrphans(ctx, repoRoot, canonical, expectedSet)
	if err != nil {
		fmt.Fprintf(stderr, "ERROR: %v\n", err)
		return 1
	}
	if check {
		for _, orphan := range orphans {
			rel, _ := filepath.Rel(repoRoot, orphan)
			drifted = append(drifted, "ORPHAN: "+filepath.ToSlash(rel))
		}
		if len(drifted) > 0 {
			for _, item := range drifted {
				fmt.Fprintln(stderr, item)
			}
			fmt.Fprintf(stderr, "ERROR: %d canonical Go file(s) out of sync. Run `python3 scripts/codegen/sync_go_canonical.py`.\n", len(drifted))
			return 1
		}
		fmt.Fprintf(stdout, "OK: %d canonical Go files are in sync.\n", len(outputs))
		return 0
	}
	if len(orphans) > 0 {
		for _, orphan := range orphans {
			rel, _ := filepath.Rel(repoRoot, orphan)
			fmt.Fprintf(stderr, "WARNING: orphan generated file not in manifest: %s\n", filepath.ToSlash(rel))
		}
		return 1
	}
	fmt.Fprintf(stdout, "Synced %d/%d canonical Go files.\n", written, len(outputs))
	return 0
}

func expectedOutputs(repoRoot, canonical string, packages []Package) (map[string]string, error) {
	out := map[string]string{}
	for _, pkg := range packages {
		for _, filename := range pkg.Files {
			rendered, err := renderFile(canonical, pkg.Name, filename)
			if err != nil {
				return nil, err
			}
			for _, target := range pkg.Targets {
				dest := filepath.Join(repoRoot, filepath.FromSlash(target), "internal", pkg.Name, filename)
				out[dest] = rendered
			}
		}
	}
	return out, nil
}

func renderFile(canonical, pkg, filename string) (string, error) {
	body, err := os.ReadFile(filepath.Join(canonical, pkg, filename))
	if err != nil {
		return "", fmt.Errorf("read canonical %s/%s: %w", pkg, filename, err)
	}
	text := string(body)
	if strings.HasPrefix(text, headerPrefix) {
		return text, nil
	}
	return generatedHdr + text, nil
}

func findOrphans(ctx context.Context, repoRoot, canonical string, expected map[string]struct{}) ([]string, error) {
	canonicalRoot, err := filepath.Abs(canonical)
	if err != nil {
		return nil, err
	}
	var paths []string
	if isGit(ctx, repoRoot) {
		paths, err = gitGoFiles(ctx, repoRoot)
	} else {
		paths, err = prunedGoFiles(repoRoot)
	}
	if err != nil {
		return nil, err
	}
	var orphans []string
	for _, path := range paths {
		if _, ok := expected[path]; ok {
			continue
		}
		abs, err := filepath.Abs(path)
		if err != nil {
			return nil, err
		}
		if abs == canonicalRoot || strings.HasPrefix(abs, canonicalRoot+string(os.PathSeparator)) {
			continue
		}
		first, err := firstLine(path)
		if err != nil {
			continue
		}
		if strings.TrimSpace(first) == headerPrefix {
			orphans = append(orphans, path)
		}
	}
	sort.Strings(orphans)
	return orphans, nil
}

func isGit(ctx context.Context, repoRoot string) bool {
	cmd := exec.CommandContext(ctx, "git", "-C", repoRoot, "rev-parse", "--is-inside-work-tree")
	out, err := cmd.Output()
	return err == nil && strings.TrimSpace(string(out)) == "true"
}

func gitGoFiles(ctx context.Context, repoRoot string) ([]string, error) {
	cmd := exec.CommandContext(ctx, "git", "-C", repoRoot, "ls-files", "-z", "--cached", "--others", "--exclude-standard", "*.go")
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git ls-files: %w", err)
	}
	var paths []string
	for _, rel := range bytes.Split(out, []byte{0}) {
		if len(rel) == 0 {
			continue
		}
		s := string(rel)
		if skipRel(s) {
			continue
		}
		paths = append(paths, filepath.Join(repoRoot, filepath.FromSlash(s)))
	}
	return paths, nil
}

func prunedGoFiles(root string) ([]string, error) {
	var paths []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() {
			if _, skip := skipScanDirs[d.Name()]; skip && path != root {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(d.Name(), ".go") {
			paths = append(paths, path)
		}
		return nil
	})
	return paths, err
}

func skipRel(rel string) bool {
	for _, part := range strings.Split(rel, "/") {
		if _, ok := skipScanDirs[part]; ok {
			return true
		}
	}
	return false
}

func firstLine(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	buf := make([]byte, 512)
	n, _ := f.Read(buf)
	text := string(buf[:n])
	if i := strings.IndexByte(text, '\n'); i >= 0 {
		return text[:i], nil
	}
	return text, nil
}

func unifiedDiff(rel string, current, expected []byte) string {
	dir, err := os.MkdirTemp("", "alt-sync-diff-*")
	if err != nil {
		return fmt.Sprintf("--- a/%s\n+++ b/%s\n%s\n", rel, rel, "diff unavailable: "+err.Error())
	}
	defer os.RemoveAll(dir)
	a := filepath.Join(dir, "a")
	b := filepath.Join(dir, "b")
	if err := os.WriteFile(a, current, fsperm.Secret); err != nil {
		return err.Error()
	}
	if err := os.WriteFile(b, expected, fsperm.Secret); err != nil {
		return err.Error()
	}
	cmd := exec.Command("diff", "-u", "--label", "a/"+rel, "--label", "b/"+rel, a, b)
	out, _ := cmd.Output()
	text := string(out)
	if text == "" {
		return fmt.Sprintf("--- a/%s\n+++ b/%s\n", rel, rel)
	}
	return text
}

func findRepoRoot() string {
	out, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	if err == nil {
		if s := strings.TrimSpace(string(out)); s != "" {
			return s
		}
	}
	// scripts/altharness/internal/codegen -> repo root is four parents up from this file's package,
	// but at runtime we use cwd's git root or walk from the executable's source layout.
	cwd, err := os.Getwd()
	if err != nil {
		return "."
	}
	return cwd
}
