func TestHeaderAndLatestPatterns(t *testing.T) {
	t.Parallel()
	headers := []struct {
		line string
		ok   bool
	}{
		{"// Code generated by oapi-codegen v2.7.0 DO NOT EDIT.", true},
		{"# Code generated by sync_python_pki.py; DO NOT EDIT.", true},
		{"// Code generated by protovis. DO NOT EDIT.", true},
		{"-- Code generated by schema-gen. DO NOT EDIT.", true},
		{"/* Code generated by token-gen. DO NOT EDIT. */", true},
		{`const hdr = "// Code generated by protovis. DO NOT EDIT."`, false},
		{"package pkg", false},
	}
	for _, tt := range headers {
		_, ok := extractGeneratedHeader(tt.line + "\n")
		if ok != tt.ok {
			t.Fatalf("header %q ok=%v want %v", tt.line, ok, tt.ok)
		}
	}
	// Line 41 is outside the 40-line window.
	var late strings.Builder
	late.WriteString("package pkg\n")
	for i := 0; i < 42; i++ {
		late.WriteByte('\n')
	}
	late.WriteString("// Code generated by late. DO NOT EDIT.\n")
	if _, ok := extractGeneratedHeader(late.String()); ok {
		t.Fatal("header after line 40 matched")
	}

	latestLines := []string{
		"\tgo run example.com/a@latest\\",
		"\tgo run example.com/b@latest|tee out",
		"\tgo run example.com/c@latest&& true",
		"RUN bunx biome@latest check",
		"//go:generate go run example.com/gogen@latest",
	}
	for _, line := range latestLines {
		if !atLatestRE.MatchString(line) {
			t.Fatalf("at-latest missed %q", line)
		}
	}
}

