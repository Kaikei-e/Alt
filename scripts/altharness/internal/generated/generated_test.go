func assertViolations(t *testing.T, vs []Violation, count int, rules ...string) {
	t.Helper()
	got := map[string]struct{}{}
	for _, v := range vs {
		got[v.Rule] = struct{}{}
	}
	want := map[string]struct{}{}
	for _, r := range rules {
		want[r] = struct{}{}
	}
	if len(vs) != count || len(got) != len(want) {
		t.Fatalf("count=%d rules=%v violations=%+v", len(vs), got, vs)
	}
	for r := range want {
		if _, ok := got[r]; !ok {
			t.Fatalf("missing %s in %+v", r, vs)
		}
	}
}

