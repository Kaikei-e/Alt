func TestPairAndC16(t *testing.T) {
	t.Parallel()
	root := altRepoRoot(t)
	before := filepath.Join(root, "scripts/harness/corpus/C-16/before.go")
	after := filepath.Join(root, "scripts/harness/corpus/C-16/after.go")
	if _, err := os.Stat(before); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(after); err != nil {
		t.Fatal(err)
	}
	code, stdout, stderr := runCLI(t, "--before", before, "--after", before)
	if code != 0 {
		t.Fatalf("identical pair code=%d out=%q err=%q", code, stdout, stderr)
	}
	code, stdout, stderr = runCLI(t, "--before", before, "--after", after)
	wantErr := after + ":1: [codegen.do-not-edit-modified] generated file carrying `DO NOT EDIT` header was modified without regenerating (header unchanged: `// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.5.1 DO NOT EDIT.`)\n"
	if code != 1 || stderr != wantErr || stdout != "" {
		t.Fatalf("tampered pair code=%d out=%q err=%q", code, stdout, stderr)
	}
	code, _, stderr = runCLI(t, "--before", before)
	if code != exitUsage {
		t.Fatalf("missing --after code=%d err=%q", code, stderr)
	}

	dir := t.TempDir()
	plainB := filepath.Join(dir, "plain_before.go")
	plainA := filepath.Join(dir, "plain_after.go")
	os.WriteFile(plainB, []byte("package foo\nfunc A() int { return 1 }\n"), fsperm.File)
	os.WriteFile(plainA, []byte("package foo\nfunc A() int { return 2 }\n"), fsperm.File)
	vs, err := checkPair(plainB, plainA, nil)
	if err != nil {
		t.Fatal(err)
	}
	assertViolations(t, vs, 0)

	genB := filepath.Join(dir, "gen_before.go")
	genA := filepath.Join(dir, "gen_stripped.go")
	os.WriteFile(genB, []byte("// Code generated by oapi-codegen v2.7.0 DO NOT EDIT.\npackage foo\n"), fsperm.File)
	os.WriteFile(genA, []byte("package foo\n// edited\n"), fsperm.File)
	vs, err = checkPair(genB, genA, nil)
	if err != nil {
		t.Fatal(err)
	}
	assertViolations(t, vs, 1, "codegen.do-not-edit-modified")
	if !strings.Contains(vs[0].Message, "header was removed") {
		t.Fatalf("message=%q", vs[0].Message)
	}
}

