-- Topic cards, candidate clusters, execution stats, and evaluation tables for recap jobs.
-- All tables are INSERT-only: no updated_at columns, no UPDATE/DELETE paths.

-- 1. Snapshot of input state frozen at job execution time (reproject-safe)
CREATE TABLE recap_card_snapshots (
    job_id UUID PRIMARY KEY REFERENCES recap_jobs(job_id),
    from_ts TIMESTAMPTZ NOT NULL,
    to_ts TIMESTAMPTZ NOT NULL,
    feed_ids UUID[] NOT NULL,
    read_feed_ids UUID[] NOT NULL DEFAULT '{}',
    previous_job_id UUID NULL,
    previous_cards JSONB NOT NULL DEFAULT '[]',
    params_version TEXT NOT NULL,
    params JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. Candidates produced by selection phase prior to LLM generation
CREATE TABLE recap_card_candidates (
    id UUID PRIMARY KEY,
    job_id UUID NOT NULL REFERENCES recap_jobs(job_id),
    rank INT NOT NULL,
    cluster_fingerprint TEXT NOT NULL,
    size INT NOT NULL,
    domains JSONB NOT NULL DEFAULT '[]',
    items JSONB NOT NULL DEFAULT '[]',
    scores JSONB NOT NULL DEFAULT '{}',
    centroid REAL[] NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (job_id, rank)
);

CREATE INDEX idx_recap_card_candidates_job_id_cluster_fingerprint
    ON recap_card_candidates (job_id, cluster_fingerprint);

-- 3. Versioned topic cards selected and generated by recap pipeline
CREATE TABLE recap_cards (
    id UUID PRIMARY KEY,
    job_id UUID NOT NULL REFERENCES recap_jobs(job_id),
    rank INT NOT NULL,
    story_id UUID NOT NULL,
    continues_card_id UUID NULL REFERENCES recap_cards(id),
    merged_from UUID[] NULL,
    headline_ja TEXT NOT NULL,
    what_ja TEXT NOT NULL,
    why_ja TEXT NULL,
    genre TEXT NULL,
    member_feed_ids UUID[] NOT NULL,
    sources JSONB NOT NULL DEFAULT '[]',
    centroid REAL[] NULL,
    scores JSONB NOT NULL DEFAULT '{}',
    gates JSONB NOT NULL DEFAULT '{}',
    generation JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (job_id, rank)
);

CREATE INDEX idx_recap_cards_story_id
    ON recap_cards (story_id);

-- 4. Pipeline execution stats and gate drop metrics
CREATE TABLE recap_card_job_stats (
    job_id UUID PRIMARY KEY REFERENCES recap_jobs(job_id),
    items_fetched INT NOT NULL,
    items_after_noise INT NOT NULL,
    items_after_dedup INT NOT NULL,
    clusters INT NOT NULL,
    candidates INT NOT NULL,
    cards_selected INT NOT NULL,
    cards_dropped JSONB NOT NULL DEFAULT '{}',
    embed_ms BIGINT NOT NULL DEFAULT 0,
    cluster_ms BIGINT NOT NULL DEFAULT 0,
    llm_ms BIGINT NOT NULL DEFAULT 0,
    total_ms BIGINT NOT NULL DEFAULT 0,
    params_version TEXT NOT NULL,
    params JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. Evaluation windows referencing replay snapshots
CREATE TABLE recap_eval_windows (
    id UUID PRIMARY KEY,
    from_ts TIMESTAMPTZ NOT NULL,
    to_ts TIMESTAMPTZ NOT NULL,
    snapshot_job_id UUID NOT NULL REFERENCES recap_jobs(job_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 6. Human golden judgments on candidate clusters (top / not_top / noise)
CREATE TABLE recap_story_judgments (
    id UUID PRIMARY KEY,
    window_id UUID NOT NULL REFERENCES recap_eval_windows(id),
    cluster_fingerprint TEXT NOT NULL,
    decision TEXT NOT NULL CHECK (decision IN ('top', 'not_top', 'noise')),
    rated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_recap_story_judgments_window_fingerprint_rated
    ON recap_story_judgments (window_id, cluster_fingerprint, rated_at DESC);

-- 7. Human ratings on generated topic cards (0/1/2 + defect flags + comment)
CREATE TABLE recap_card_ratings (
    id UUID PRIMARY KEY,
    card_id UUID NOT NULL REFERENCES recap_cards(id),
    score SMALLINT NOT NULL CHECK (score BETWEEN 0 AND 2),
    flags TEXT[] NOT NULL DEFAULT '{}',
    comment TEXT NULL,
    rated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_recap_card_ratings_card_rated
    ON recap_card_ratings (card_id, rated_at DESC);
